// 坏模式必须在写产物前拒绝（已有产物不变），正常参数 / 正则 / 通配符沿用 chi 的写法。
func TestGenerateRejectsMalformedPatternsWithoutChangingOutput(t *testing.T) {
	for _, path := range []string{"/broken/{id", "/broken/{id:[}", "/broken/*/tail"} {
		t.Run(path, func(t *testing.T) {
			dir := t.TempDir()
			source := strings.Replace(webRouteSource, "/external/json", path, 1)
			if err := os.WriteFile(filepath.Join(dir, "handler.go"), []byte(source), 0600); err != nil {
				t.Fatal(err)
			}
			output := filepath.Join(dir, generatedFileName)
			before := []byte("// Code generated by roost webroute. DO NOT EDIT.\n\npackage web\n")
			if err := os.WriteFile(output, before, 0600); err != nil {
				t.Fatal(err)
			}
			_, err := GenerateDir(dir, true)
			if err == nil || !strings.Contains(err.Error(), "handleJSON") || !strings.Contains(err.Error(), path) {
				t.Fatalf("generation should reject handler/path: %v", err)
			}
			after, err := os.ReadFile(output)
			if err != nil || !bytes.Equal(before, after) {
				t.Fatalf("existing output changed: %q err=%v", after, err)
			}
		})
	}
}

