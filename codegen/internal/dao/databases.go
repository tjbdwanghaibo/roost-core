// databasesFileName 是 DAO 包里的逻辑库常量文件（DESIGN-TODO D9 修订版 A）：工程全部 DAO 的 db= 去重后
// 每个逻辑库一个常量，各 DAO 的 <Dao>DBName 引用它；init 里把它们登记给 DataEngine（dataengine.DeclareDatabases），
// 运行时的映射表只认登记过的逻辑库，配置里拼错的名字在启动时被点名拒绝。
const databasesFileName = "gen_databases.go"

// databaseConstName 是逻辑库 db= 的常量名：Database + 逻辑名的 PascalCase（main → DatabaseMain）。
func databaseConstName(logical string) string {
	var b strings.Builder
	b.WriteString("Database")
	for _, part := range strings.Split(logical, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// logicalDatabaseName 与运行期 framework/dataengine 的 ValidLogicalDatabaseName 是同一条规则：小写字母开头，
// 小写字母、数字与下划线，不超过 Mongo 库名上限 63 字节（没有映射时它就是物理库名）。生成器不得 import 运行时
// （根包 TestCoreDependencyBoundary），所以在这里写一份；两边不一致时生成的 gen_databases.go 会在 init 里被
// dataengine.DeclareDatabases 拒绝（panic），进程起不来，不会静默放过。
var logicalDatabaseName = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

func validateDatabaseName(name string) error {
	if !logicalDatabaseName.MatchString(name) {
		return fmt.Errorf("want a lowercase name matching %s", logicalDatabaseName)
	}
	if len(name) > 63 {
		return fmt.Errorf("%d bytes; Mongo database names allow 63", len(name))
	}
	switch name {
	case "admin", "local", "config":
		return fmt.Errorf("%q is a Mongo system database; a logical name without a mapping is used as the physical name", name)
	}
	return nil
}

type databaseDecl struct {
	Const        string
	Name         string
	ServerScoped bool
	Daos         []string
}

// collectDatabases 去重全部持久 DAO 的 db=；常量名撞车（例如 a_1 与 a1）时拒绝，指出是哪两个逻辑库。
func collectDatabases(daos []DaoDef) ([]databaseDecl, error) {
	byName := map[string]*databaseDecl{}
	for _, dao := range daos {
		if dao.NoCollection {
			continue
		}
		decl := byName[dao.Db]
		if decl == nil {
			decl = &databaseDecl{Const: databaseConstName(dao.Db), Name: dao.Db}
			byName[dao.Db] = decl
		}
		decl.ServerScoped = decl.ServerScoped || dao.DbScope == "sid"
		decl.Daos = append(decl.Daos, dao.Name)
	}
	out := make([]databaseDecl, 0, len(byName))
	owners := map[string]string{}
	for _, name := range slices.Sorted(func(yield func(string) bool) {
		for name := range byName {
			if !yield(name) {
				return
			}
		}
	}) {
		decl := byName[name]
		if other, ok := owners[decl.Const]; ok {
			return nil, fmt.Errorf("logical databases %q and %q both generate the constant %s; rename one db=", other, name, decl.Const)
		}
		owners[decl.Const] = name
		slices.Sort(decl.Daos)
		out = append(out, *decl)
	}
	return out, nil
}

var databasesTemplate = `// Code generated by tool/dao. DO NOT EDIT.
package {{.Package}}

import "github.com/tjbdwanghaibo/roost-core/framework/dataengine"

// 本工程 DAO 标记 db= 用到的逻辑库名。它们不是 Mongo 库名：物理库名由部署决定（服务配置
// dataengine.databases 或启动装配时注册的 kitdataengine.WithDatabaseResolver），DataEngine 启动时合成一张
// 冻结的映射表，投影、冷加载、Remote 存储与运维工具都经它换算。业务代码要直接打开 DAO 所在的库时，从
// mods.ModDataEngineDatabases 取 *dataengine.DatabaseMap 再 Physical(逻辑名)，不要把这些常量直接当库名。
const (
{{- range .Databases}}
	// {{.Const}} 是 {{range $i, $d := .Daos}}{{if $i}}、{{end}}{{$d}}{{end}} 的逻辑库{{if .ServerScoped}}（含按 sid 分库的 DAO，物理名再加 _<sid>）{{end}}。
	{{.Const}} = "{{.Name}}"
{{- end}}
)

func init() {
	dataengine.DeclareDatabases(
{{- range .Databases}}
		dataengine.LogicalDatabase{Name: {{.Const}}, ServerScoped: {{.ServerScoped}}},
{{- end}}
	)
}
`

func generateDatabases(databases []databaseDecl, pkg string, outFile string, force bool) (bool, error) {
	tmpl, err := template.New("databases").Parse(databasesTemplate)
	if err != nil {
		return false, fmt.Errorf("template parse: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct {
		Package   string
		Databases []databaseDecl
	}{pkg, databases}); err != nil {
		return false, fmt.Errorf("template exec: %w", err)
	}
	content, err := format.Source(buf.Bytes())
	if err != nil {
		return false, fmt.Errorf("format generated databases: %w", err)
	}
	return writeIfChanged(content, outFile, force)
}
