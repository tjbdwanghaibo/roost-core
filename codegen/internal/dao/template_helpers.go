package dao

// bsonHelpersFileName is the one file per package holding the generic
// container conversions the nested wire forms use.
const bsonHelpersFileName = "gen_dao_bson_helpers.go"

// bsonHelpersTemplate is written once per output package that has nested
// structs. The two functions map a per-type conversion over a map or a slice
// in either direction (stored form <-> wire form); see wireType in gen.go.
var bsonHelpersTemplate = `// Code generated by tool/dao. DO NOT EDIT.
package {{.Package}}

import (
	"fmt"

	"github.com/tjbdwanghaibo/roost-core/dataengine"
)

// daoMapDocs maps conv over src; nil stays nil so an absent map is not
// persisted as an empty one.
func daoMapDocs[K comparable, V, D any](src map[K]V, conv func(V) D) map[K]D {
	if src == nil {
		return nil
	}
	out := make(map[K]D, len(src))
	for key, val := range src {
		out[key] = conv(val)
	}
	return out
}

// daoSliceDocs maps conv over src; nil stays nil.
func daoSliceDocs[V, D any](src []V, conv func(V) D) []D {
	if src == nil {
		return nil
	}
	out := make([]D, len(src))
	for i, val := range src {
		out[i] = conv(val)
	}
	return out
}

// daoDirtyOwner identifies the ONE place a nested value belongs to: which
// object holds it, which field of that object, and which key or index within
// the field.
//
// A nested value reports its changes through a single notification slot, so a
// value put in two places reports to whichever place bound it last — and the
// other place silently stops being persisted while memory shows both equal
// (RR-20260919-02). Neither "last wins" nor "first wins" is a correct answer,
// so the model is unique parent ownership: one parent at a time, and an
// attempt to take a value that already has one is refused at the call.
//
// It is comparable, and every part of it is: the holder is a pointer, the
// field is a generated ordinal and the key is a map key or a slice index,
// which Go requires to be comparable anyway.
type daoDirtyOwner struct {
	holder any
	field  uint64
	key    any
}

func (owner daoDirtyOwner) held() bool { return owner.holder != nil }

// daoBindDirty is what every generated bind site calls. It refuses rather than
// overwriting, and it refuses BEFORE anything is written, so a caller that
// recovers is left with the state it started from.
func daoBindDirty(hook *dataengine.DirtyHook, current *daoDirtyOwner, owner daoDirtyOwner, typeName string, notify func()) {
	if hook == nil || current == nil {
		return
	}
	if current.held() && *current != owner {
		panic(fmt.Sprintf(
			"dao: %s already has a parent (field %d, key %v of %T) and a nested value may have one parent at a time; "+
				"take it out of the first place (Del / Set nil / assign another value) before putting it in the second, "+
				"or store a copy if the two places are meant to be independent",
			typeName, current.field, current.key, current.holder))
	}
	*current = owner
	hook.SetNotify(notify)
}

// daoUnbindDirty releases a binding, and only its own: a stale unbind from a
// place the value has already left must not silence the place it is in now.
func daoUnbindDirty(hook *dataengine.DirtyHook, current *daoDirtyOwner, owner daoDirtyOwner) {
	if hook == nil || current == nil || *current != owner {
		return
	}
	*current = daoDirtyOwner{}
	hook.SetNotify(nil)
}
`

// fieldCarriesChildHook reports whether a nested struct's field holds nested
// children whose changes have to reach this struct through a callback. Those
// are the fields that need bind/unbind helpers: which child notifies which
// parent is runtime wiring, and it has to be re-established on every path
// that changes what the field holds — the setter, a restore from storage, and
// the rollback undo (RR-20260918-03).
func fieldCarriesChildHook(defs *Definitions, f FieldDef) bool {
	switch f.Kind {
	case 1:
		return f.IsPtr && isNestedType(defs, f.SliceElem)
	case 2:
		return f.IsPtr && isNestedType(defs, f.MapVal)
	case 3:
		return isNestedType(defs, f.TypeStr)
	}
	return false
}

// fieldDetachesOldChildren narrows fieldCarriesChildHook to the fields whose
// previous contents survive the assignment as separate objects and therefore
// have to be released. A nested value field is overwritten in place — there is
// no old object left to notify anyone — so it is bound but never unbound.
func fieldDetachesOldChildren(defs *Definitions, f FieldDef) bool {
	return fieldCarriesChildHook(defs, f) && (f.Kind != 3 || f.IsPtr)
}
