package nest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// sender 的 nil client 守卫是生成代码，执行它的是生成在 sender 包旁边的配套测试。
func TestGenerateSenderGuardTest(t *testing.T) {
	dir := t.TempDir()
	senderFile := filepath.Join(dir, "handler_nest_gen.go")
	changed, err := generateSenderGuardTest("handler_sender", senderFile, true)
	if err != nil || !changed {
		t.Fatalf("generateSenderGuardTest = (%v, %v)", changed, err)
	}
	raw, err := os.ReadFile(guardTestFileFor(senderFile))
	if err != nil {
		t.Fatal(err)
	}
	generated := string(raw)
	sender := senderTypeName(senderFile)
	for _, required := range []string{
		"// Code generated by tool/nest. DO NOT EDIT.",
		"package handler_sender",
		"func Test" + sender + "RefusesCallsWithoutAClient(t *testing.T)",
		"var none *" + sender,
		"New" + sender + "(nil).nestClient()",
		"nest.ErrNestStopped",
	} {
		if !strings.Contains(generated, required) {
			t.Errorf("sender guard test missing %q:\n%s", required, generated)
		}
	}
	again, err := generateSenderGuardTest("handler_sender", senderFile, false)
	if err != nil || again {
		t.Fatalf("second run = (%v, %v), want unchanged", again, err)
	}
}
