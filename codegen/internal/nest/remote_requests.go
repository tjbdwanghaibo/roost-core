package nest

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

// generateRemoteRequests 按类型声明生成，而非按引用它的 handler 生成。
// 请求可以放在 game 下的共用包；多个 handler 共用时只生成一份方法，也不会让 Sender 反向导入 handler。
func generateRemoteRequests(path string, force bool) (string, bool, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", false, err
	}
	if !bytes.Contains(raw, []byte("remote:")) {
		return "", false, nil
	}
	file, err := parser.ParseFile(token.NewFileSet(), path, raw, parser.ParseComments)
	if err != nil {
		return "", false, err
	}
	fields, err := collectRemoteStructFields(file)
	if err != nil {
		return "", false, err
	}
	if len(fields) == 0 {
		return "", false, nil
	}
	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}
	sort.Strings(names)
	var funcs []*FuncInfo
	used := map[string]bool{}
	for _, name := range names {
		fn := &FuncInfo{Params: []NonEntityParam{{Name: "req", Type: name}}}
		attachRemoteStructFieldAccess(fn, fields)
		for _, access := range fn.RemoteAccess {
			for _, expr := range []string{access.Type, access.Scope, access.Tenant, access.Policy, access.MinVersion, access.CacheTTLMillis} {
				for _, alias := range packageRefs(expr) {
					if alias != "req" {
						used[alias] = true
					}
				}
			}
		}
		funcs = append(funcs, fn)
	}
	var imports []ImportInfo
	for _, spec := range file.Imports {
		imp := importInfoFromSpec(spec)
		alias := imp.Alias
		if alias == "" {
			alias = filepath.Base(imp.Path)
		}
		if used[alias] && alias != "entity" && alias != "nest" {
			imports = append(imports, imp)
		}
		delete(used, alias)
	}
	delete(used, "entity")
	delete(used, "nest")
	if len(used) != 0 {
		aliases := make([]string, 0, len(used))
		for alias := range used {
			aliases = append(aliases, alias)
		}
		sort.Strings(aliases)
		return "", false, fmt.Errorf("nest: remote request uses package %q; import it in the request source file", aliases[0])
	}
	tmpl, err := template.New("remote_requests").Funcs(template.FuncMap{
		"remoteParamAccessors": remoteParamAccessors, "remoteKeyName": remoteKeyName,
		"quote":                 func(s string) string { return fmt.Sprintf("%q", s) },
		"remoteConsistencyExpr": remoteConsistencyExpr, "remoteScopeExpr": remoteScopeExpr, "remoteTTLExpr": remoteTTLExpr,
	}).Parse(remoteRequestsTemplate)
	if err != nil {
		return "", false, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct {
		Package string
		Imports []ImportInfo
		Funcs   []*FuncInfo
	}{file.Name.Name, imports, funcs}); err != nil {
		return "", false, err
	}
	content, err := format.Source(buf.Bytes())
	if err != nil {
		return "", false, fmt.Errorf("format remote requests: %w", err)
	}
	out := strings.TrimSuffix(path, ".go") + "_remote_nest_gen.go"
	old, _ := os.ReadFile(out)
	if !force && bytes.Equal(old, content) {
		return out, false, nil
	}
	if err := os.WriteFile(out, content, 0644); err != nil {
		return "", false, err
	}
	return out, true, nil
}

const remoteRequestsTemplate = `// Code generated by tool/nest. DO NOT EDIT.
package {{.Package}}

import (
 "github.com/tjbdwanghaibo/roost-core/framework/entity"
 "github.com/tjbdwanghaibo/roost-core/framework/nest"
 {{range .Imports}}{{.Alias}} "{{.Path}}"
 {{end}}
)

// RemoteAccess 只声明读取依赖，由 Nest 在 I/O 阶段准备；访问器只在当前 handler 内读取已准备的快照。
{{range remoteParamAccessors .Funcs}}
{{- $paramType := .ParamType}}
{{- $paramName := .ParamName}}
{{- range .Accesses}}
var {{remoteKeyName $paramType .Accessor}} = nest.RemoteKey[{{.Type}}]{Alias: {{quote .Alias}}}
{{- end}}

func ({{.ParamName}} {{.ParamType}}) RemoteAccess() []nest.RemoteAccess {
	return []nest.RemoteAccess{
{{- range .Accesses}}
		{
			Alias: {{quote .Alias}},
			Ref: {{.RefExpr}},
			Consistency: {{remoteConsistencyExpr .Consistency}},
			Scope: {{remoteScopeExpr .}},
			Tenant: {{if .Tenant}}{{.Tenant}}{{else}}0{{end}},
			Policy: {{if .Policy}}{{.Policy}}{{else}}0{{end}},
			MinVersion: {{if .MinVersion}}{{.MinVersion}}{{else}}0{{end}},
			{{- if .AllowStale}}
			AllowStale: true,
			{{- end}}
			CacheTTLMillis: {{remoteTTLExpr .}},
			{{- if .Required}}
			Required: true,
			{{- end}}
		},
{{- end}}
	}
}
{{range .Accesses}}
func ({{$paramName}} {{$paramType}}) {{.Accessor}}() ({{.Type}}, bool) {
	return nest.Remote({{remoteKeyName $paramType .Accessor}})
}

func ({{$paramName}} {{$paramType}}) Must{{.Accessor}}() {{.Type}} {
	return nest.MustRemote({{remoteKeyName $paramType .Accessor}})
}
{{end}}
{{end}}

`
