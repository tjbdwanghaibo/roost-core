package nest

import (
	"bytes"
	"crypto/md5"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"text/template"

	"github.com/tjbdwanghaibo/roost-core/codegen/internal/entityowner"
)

// 本地实体起服预加载（//roost:entity preload=startup [preload_order=<N>]，维护者 2026-11-13）在 Nest 生成里只有一件事：
// internal/registry/preload_gen.go 列出这些 kind 与它们的归属服务（service=，没写为 ""），给出
// LocalPreloadKinds(service)。bootstrap 把它交给预加载服务的 kitdataengine.NewLocalPreloadMod；哪个服务预加载
// 没写 service= 的 kind 由 roost project sync 按 roost.yaml 决定（只能有一个候选服务）。批次（preload_order）
// 不在这里：它由实体生成器写进 EntityBuilderParam.LoadPriority，运行期按它分批。没有本地预加载时删除这个文件。

type localPreloadKind struct {
	Expr    string // alias.EntityKindPlayer
	Service string
}

type localPreloadFile struct {
	Imports []bootstrapPackage
	Kinds   []localPreloadKind
}

func generateLocalPreload(gameDir, moduleRoot, modulePath, outFile string, force bool) (bool, error) {
	preloads, err := entityowner.LocalPreloads(gameDir)
	if err != nil {
		return false, err
	}
	if len(preloads) == 0 {
		if err := os.Remove(outFile); err == nil {
			return true, nil
		} else if !os.IsNotExist(err) {
			return false, err
		}
		return false, nil
	}
	used := map[string]string{}
	var data localPreloadFile
	for _, item := range preloads {
		importPath, err := importPathForDir(moduleRoot, modulePath, item.Dir)
		if err != nil {
			return false, err
		}
		kind := item.Kind
		if !strings.Contains(kind, ".") {
			alias := ""
			for existingAlias, existing := range used {
				if existing == importPath {
					alias = existingAlias
				}
			}
			if alias == "" {
				alias = uniqueBootstrapAlias(importPath, used)
				used[alias] = importPath
			}
			kind = alias + "." + kind
		}
		data.Kinds = append(data.Kinds, localPreloadKind{Expr: kind, Service: item.Service})
	}
	for alias, importPath := range used {
		data.Imports = append(data.Imports, bootstrapPackage{Alias: alias, ImportPath: importPath})
	}
	sort.Slice(data.Imports, func(i, j int) bool { return data.Imports[i].ImportPath < data.Imports[j].ImportPath })
	tmpl, err := template.New("preload").Parse(localPreloadTemplate)
	if err != nil {
		return false, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return false, err
	}
	content, err := format.Source(buf.Bytes())
	if err != nil {
		return false, fmt.Errorf("format local preload: %w\n%s", err, buf.String())
	}
	if !force {
		if existing, err := os.ReadFile(outFile); err == nil && md5.Sum(existing) == md5.Sum(content) {
			return false, nil
		}
	}
	return true, os.WriteFile(outFile, content, 0o644)
}

const localPreloadTemplate = `// Code generated by tool/nest. DO NOT EDIT.

package registry

import (
	"slices"

	"github.com/tjbdwanghaibo/roost-core/framework/entity"
{{- range .Imports }}
	{{ .Alias }} "{{ .ImportPath }}"
{{- end }}
)

// localPreloadOwners 是声明了 preload=startup 的本地 kind 与它的归属服务（service=，没写为 ""）。这些实体在起服时从
// 本服库（dbscope=sid）加载进内存，批次是实体标记的 preload_order（EntityBuilderParam.LoadPriority）。
var localPreloadOwners = map[entity.EntityKind]string{
{{- range .Kinds }}
	{{ .Expr }}: "{{ .Service }}",
{{- end }}
}

// LocalPreloadKinds 返回 service 起服时预加载的本地 kind（排序）：归属 service 的，加上没有声明归属的。
// bootstrap 只给预加载服务装 kitdataengine.NewLocalPreloadMod(registry.LocalPreloadKinds("<service>")...)。
func LocalPreloadKinds(service string) []entity.EntityKind {
	var out []entity.EntityKind
	for kind, owner := range localPreloadOwners {
		if owner == "" || owner == service {
			out = append(out, kind)
		}
	}
	slices.Sort(out)
	return out
}
`
