// opsPort gives every service its own ops listener on a developer machine, so
// the processes a project declares can run side by side without editing
// configs: business services in name order from 9100, then the hosted
// framework services. Production configs keep 9100 everywhere — there each
// process has its own container, and the Dockerfile / manifests expose 9100.
func opsPort(m Manifest, service string) int {
	port := 9100
	for _, name := range sortedServiceNames(m) {
		if m.isFrameworkService(name) {
			continue
		}
		if name == service {
			return port
		}
		port++
	}
	for _, name := range sortedServiceNames(m) {
		if !m.isFrameworkService(name) {
			continue
		}
		if name == service {
			return port
		}
		port++
	}
	return port
}

// devRunOrder is the order deploy/dev/run.sh starts processes: the hosted
// framework services first (the business service looks their capabilities up
// in Init and would fail without them), then the business services.
func devRunOrder(m Manifest) []string {
	var order []string
	for _, name := range sortedServiceNames(m) {
		if m.isFrameworkService(name) {
			order = append(order, name)
		}
	}
	for _, name := range sortedServiceNames(m) {
		if !m.isFrameworkService(name) {
			order = append(order, name)
		}
	}
	return order
}

// renderDevRun writes deploy/dev/run.sh: start every declared service against
// the dev compose infrastructure, wait for each one's /readyz, register the
// game server with the account service when the project has accountctl, and
// stop / show status / tail logs. It is what `make dev-run` runs; pids and
// logs live under .dev/.
func renderDevRun(m Manifest) string {
	var services []string
	for _, name := range devRunOrder(m) {
		services = append(services, fmt.Sprintf("%s:%d", name, opsPort(m, name)))
	}
	var b strings.Builder
	b.WriteString("#!/usr/bin/env sh\n# Code generated by roost-codegen. DO NOT EDIT.\n")
	b.WriteString("# Run every service of this project on one machine against deploy/dev/docker-compose.yaml.\n")
	b.WriteString("#   sh deploy/dev/run.sh start|stop|status|logs [service]\n")
	b.WriteString("# Each service gets its own ops port (configs/service/config.<svc>.yaml ops.addr) so they coexist;\n")
	b.WriteString("# pids and logs are under .dev/. SID and READY_TIMEOUT are overridable from the environment.\n")
	b.WriteString("set -eu\n\n")
	b.WriteString("SERVICES=\"" + strings.Join(services, " ") + "\"\n")
	b.WriteString("SID=\"${SID:-1000}\"\nREADY_TIMEOUT=\"${READY_TIMEOUT:-90}\"\nDEV_DIR=\".dev\"\nBIN=\"bin/app\"\n\n")
	b.WriteString(`name_of() { printf '%s' "$1" | cut -d: -f1; }
port_of() { printf '%s' "$1" | cut -d: -f2; }

ready_url() {
  # ops.addr from the service's config; 0.0.0.0 is reachable as 127.0.0.1.
  addr=$(awk '/^ops:/{o=1;next} o&&/^  addr:/{print $2;exit} o&&/^[^ ]/{o=0}' "configs/service/config.$1.yaml" | tr -d '"')
  [ -n "$addr" ] || addr="127.0.0.1:$2"
  printf 'http://%s/readyz' "$(printf '%s' "$addr" | sed 's/^0\.0\.0\.0/127.0.0.1/')"
}

wait_ready() {
  url=$(ready_url "$1" "$2")
  i=0
  while [ "$i" -lt "$READY_TIMEOUT" ]; do
    if command -v curl >/dev/null 2>&1; then
      curl -fsS -o /dev/null "$url" 2>/dev/null && return 0
    else
      sleep 2 && return 0
    fi
    if [ -f "$DEV_DIR/$1.pid" ] && ! kill -0 "$(cat "$DEV_DIR/$1.pid")" 2>/dev/null; then
      echo "$1 exited before it was ready; last log lines:" >&2
      tail -n 30 "$DEV_DIR/$1.log" >&2
      return 1
    fi
    i=$((i + 1))
    sleep 1
  done
  echo "$1 did not answer $url within ${READY_TIMEOUT}s; last log lines:" >&2
  tail -n 30 "$DEV_DIR/$1.log" >&2
  return 1
}

start_one() {
  svc=$(name_of "$1"); port=$(port_of "$1")
  if [ -f "$DEV_DIR/$svc.pid" ] && kill -0 "$(cat "$DEV_DIR/$svc.pid")" 2>/dev/null; then
    echo "$svc already running (pid $(cat "$DEV_DIR/$svc.pid"))"
    return 0
  fi
  echo "starting $svc (ready probe $(ready_url "$svc" "$port"), log $DEV_DIR/$svc.log)"
  nohup "$BIN" "$svc" --sid "$SID" --config "configs/service/config.$svc.yaml" >"$DEV_DIR/$svc.log" 2>&1 &
  echo $! >"$DEV_DIR/$svc.pid"
  wait_ready "$svc" "$port"
}

register_game_server() {
  # The account service only lets a role be created on a server it knows.
  # accountctl is part of the game-demo template; other projects register
  # servers however their account collaborators decide.
  if [ -d cmd/accountctl ] && [ -f configs/service/config.account.yaml ]; then
    redis=$(awk '/^redis:/{r=1;next} r&&/^  addr:/{print $2;exit} r&&/^[^ ]/{r=0}' configs/service/config.account.yaml | tr -d '"')
    prefix=$(awk '/^account:/{a=1;next} a&&/^  key_prefix:/{print $2;exit} a&&/^[^ ]/{a=0}' configs/service/config.account.yaml | tr -d '"')
    echo "registering game server $SID with the account service"
    go run ./cmd/accountctl -redis "${redis:-127.0.0.1:6379}" -prefix "${prefix:-roost:account}" upsert-server -sid "$SID" >/dev/null
  fi
}

cmd_start() {
  mkdir -p "$DEV_DIR"
  echo "building $BIN"
  go build -o "$BIN" .
  for entry in $SERVICES; do
    if [ -n "${1:-}" ] && [ "$(name_of "$entry")" != "$1" ]; then continue; fi
    start_one "$entry"
  done
  [ -n "${1:-}" ] || register_game_server
  echo "all services ready; logs in $DEV_DIR/, stop with: sh deploy/dev/run.sh stop"
}

cmd_stop() {
  # Reverse start order: the business service goes first, the ones it uses last.
  for entry in $(printf '%s\n' $SERVICES | awk '{a[NR]=$0} END{for(i=NR;i>0;i--)print a[i]}'); do
    svc=$(name_of "$entry")
    if [ -n "${1:-}" ] && [ "$svc" != "$1" ]; then continue; fi
    if [ -f "$DEV_DIR/$svc.pid" ]; then
      pid=$(cat "$DEV_DIR/$svc.pid")
      if kill -0 "$pid" 2>/dev/null; then
        echo "stopping $svc (pid $pid)"
        kill "$pid" 2>/dev/null || true
        i=0; while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 30 ]; do i=$((i + 1)); sleep 1; done
        kill -0 "$pid" 2>/dev/null && kill -9 "$pid" 2>/dev/null || true
      fi
      rm -f "$DEV_DIR/$svc.pid"
    fi
  done
}

cmd_status() {
  for entry in $SERVICES; do
    svc=$(name_of "$entry"); port=$(port_of "$entry")
    if [ -f "$DEV_DIR/$svc.pid" ] && kill -0 "$(cat "$DEV_DIR/$svc.pid")" 2>/dev/null; then
      echo "$svc: running (pid $(cat "$DEV_DIR/$svc.pid"), $(ready_url "$svc" "$port"))"
    else
      echo "$svc: stopped"
    fi
  done
}

cmd_logs() {
  if [ -n "${1:-}" ]; then tail -f "$DEV_DIR/$1.log"; else tail -f "$DEV_DIR"/*.log; fi
}

case "${1:-}" in
  start) cmd_start "${2:-}" ;;
  stop) cmd_stop "${2:-}" ;;
  restart) cmd_stop "${2:-}"; cmd_start "${2:-}" ;;
  status) cmd_status ;;
  logs) cmd_logs "${2:-}" ;;
  *) echo "usage: sh deploy/dev/run.sh start|stop|restart|status|logs [service]" >&2; exit 2 ;;
esac
`)
	return b.String()
}

// renderSecondGame writes deploy/dev/second-game.sh: a SECOND process of the
// business service, against the same infrastructure the first one uses.
//
// It exists because "two processes" is the configuration that finds the bugs
// a single process cannot have — two writers of one document, work delivered
// to whichever process is free rather than the one that owns the object — and
// because reproducing it by hand means getting four overrides right. Each one
// is a hard requirement, not a preference:
//
//	sid         the bus addresses a process as <prefix>.svc.<type>.<sid>, and
//	            two processes sharing a sid cannot be addressed apart
//	ops.addr    the /readyz and metrics listener, one per process
//	client port the player TCP listener
//	WAL dir     nestwal takes an exclusive lock on its directory and correctly
//	            refuses the second process otherwise
//
// The demo's ownership table (game/playerroute) is what makes this safe; see
// GAME_DEMO_TEMPLATE §9.11 and §9.12 for what it does and does not cover.
func renderSecondGame(m Manifest, gameService string) string {
	return fmt.Sprintf(`#!/usr/bin/env sh
# Code generated by roost-codegen. DO NOT EDIT.
# A second %[1]s process on this machine, against the same Mongo / Redis / NATS.
#   sh deploy/dev/run.sh start            # the first process and every service
#   sh deploy/dev/second-game.sh start    # this one, afterwards
#   sh deploy/dev/second-game.sh stop
#
# Config is derived from configs/service/config.%[1]s.yaml the first time and
# written to configs/service/config.%[1]s2.yaml; edit that file to keep changes.
set -eu

SERVICE="%[1]s"
SID="${SECOND_SID:-%[2]d}"
OPS_PORT="${SECOND_OPS_PORT:-%[3]d}"
CLIENT_PORT="${SECOND_CLIENT_PORT:-%[4]d}"
SOURCE="configs/service/config.$SERVICE.yaml"
TARGET="configs/service/config.${SERVICE}2.yaml"
DEV_DIR=".dev"
BIN="bin/app"
PID_FILE="$DEV_DIR/${SERVICE}2.pid"
LOG_FILE="$DEV_DIR/${SERVICE}2.log"
READY_TIMEOUT="${READY_TIMEOUT:-90}"

derive_config() {
  [ -f "$TARGET" ] && return 0
  [ -f "$SOURCE" ] || { echo "$SOURCE not found; run from the project root" >&2; exit 1; }
  # Four overrides, each of which the second process cannot start without.
  sed \
    -e "s/^\(  *\)sid: .*/\1sid: $SID/" \
    -e "s#^\(  *\)addr: \(.*\):%[5]d\$#\1addr: \2:$OPS_PORT#" \
    -e "s#^\(  *\)addr: \(.*\):%[6]d\$#\1addr: \2:$CLIENT_PORT#" \
    -e "s#^\(  *\)dir: \(.*\)/wal/dataengine\$#\1dir: \2/wal/dataengine-$SID#" \
    "$SOURCE" > "$TARGET"
  echo "wrote $TARGET (sid $SID, ops $OPS_PORT, client $CLIENT_PORT, its own WAL directory)"
}

ready_url() {
  addr=$(awk '/^ops:/{o=1;next} o&&/^  addr:/{print $2;exit} o&&/^[^ ]/{o=0}' "$TARGET" | tr -d '"')
  [ -n "$addr" ] || addr="127.0.0.1:$OPS_PORT"
  printf 'http://%%s/readyz' "$(printf '%%s' "$addr" | sed 's/^0\.0\.0\.0/127.0.0.1/')"
}

cmd_start() {
  derive_config
  mkdir -p "$DEV_DIR"
  if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    echo "${SERVICE}2 already running (pid $(cat "$PID_FILE"))"; return 0
  fi
  # Refuse to start if something already answers on this ops port. Without
  # this check a leftover process from an earlier run answers the readiness
  # probe, the script reports success, and the process it actually started is
  # already dead of "address already in use" — a false green that costs an
  # afternoon to see.
  if curl -fsS -o /dev/null "$(ready_url)" 2>/dev/null; then
    echo "something is already listening on the ops port ($(ready_url)); stop it first, or set SECOND_OPS_PORT" >&2
    exit 1
  fi
  [ -x "$BIN" ] || go build -o "$BIN" .
  "$BIN" "$SERVICE" --sid "$SID" --config "$TARGET" > "$LOG_FILE" 2>&1 &
  echo $! > "$PID_FILE"
  url=$(ready_url)
  i=0
  while [ "$i" -lt "$READY_TIMEOUT" ]; do
    # Liveness first: a process that has exited cannot be the one answering.
    kill -0 "$(cat "$PID_FILE")" 2>/dev/null || { echo "${SERVICE}2 exited; see $LOG_FILE" >&2; tail -3 "$LOG_FILE" >&2; exit 1; }
    if curl -fsS -o /dev/null "$url" 2>/dev/null; then
      echo "${SERVICE}2 ready on sid $SID (ops $url, client port $CLIENT_PORT); logs in $LOG_FILE"
      return 0
    fi
    i=$((i + 1)); sleep 1
  done
  echo "${SERVICE}2 did not become ready in ${READY_TIMEOUT}s; see $LOG_FILE" >&2
  exit 1
}

cmd_stop() {
  [ -f "$PID_FILE" ] || { echo "${SERVICE}2 not running"; return 0; }
  pid=$(cat "$PID_FILE")
  kill "$pid" 2>/dev/null || true
  i=0
  while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 30 ]; do i=$((i + 1)); sleep 1; done
  rm -f "$PID_FILE"
  echo "${SERVICE}2: stopped"
}

case "${1:-}" in
  start) cmd_start ;;
  stop) cmd_stop ;;
  restart) cmd_stop; cmd_start ;;
  logs) tail -f "$LOG_FILE" ;;
  *) echo "usage: sh deploy/dev/second-game.sh start|stop|restart|logs" >&2; exit 2 ;;
esac
`, gameService, secondGameSID, opsPort(m, gameService)+10, secondGameClientPort, opsPort(m, gameService), firstGameClientPort)
}

const (
	// secondGameSID is the second process's server id. A game server is one
	// process here, so this is a different server: its World, its activity
	// lease and its bus address are all its own.
	secondGameSID = 1001
	// The player TCP listener the demo generates, and the port the second
	// process moves to.
	firstGameClientPort  = 7000
	secondGameClientPort = 7001
)

// firstBusinessService is the process deploy/dev/second-game.sh runs a second
// copy of: the project's own service, not a hosted framework one. A project
// with only framework services has nothing to run twice.
func firstBusinessService(m Manifest) string {
	for _, name := range sortedServiceNames(m) {
		if !m.isFrameworkService(name) {
			return name
		}
	}
	return ""
}
