package roost

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/tjbdwanghaibo/roost-core/codegen/internal/marker"
)

const endpointGeneratedHeader = "// Code generated by roost endpoint. DO NOT EDIT."

// generateEndpoints 以手写 Controller 方法为唯一声明源；生成文件不反过来决定业务接线。
// 删除声明只退役本生成器自己的文件，手写入口与 controller.go 永不删除。
func generateEndpoints(root string, manifest Manifest, stdout io.Writer) error {
	dir := filepath.Join(root, "game", "controllers")
	expected := map[string]bool{}
	var owned []string
	var changes []syncChange
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, walkErr error) error {
		if os.IsNotExist(walkErr) && path == dir {
			return nil
		}
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(raw, []byte(endpointGeneratedHeader+"\n")) {
			owned = append(owned, path)
			return nil
		}
		if hasGeneratedHeader(path, raw) {
			return nil
		}
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, raw, parser.ParseComments)
		if err != nil {
			return err
		}
		if err := marker.CheckFile(fset, file, marker.Endpoint); err != nil {
			return err
		}
		marked, bound := 0, 0
		for _, group := range file.Comments {
			for _, comment := range group.List {
				if _, ok := marker.Cut(comment.Text, "endpoint"); ok {
					marked++
				}
			}
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Doc == nil {
				continue
			}
			for _, comment := range fn.Doc.List {
				rest, ok := marker.Cut(comment.Text, "endpoint")
				if !ok {
					continue
				}
				bound++
				if fn.Recv == nil || len(fn.Recv.List) != 1 || !strings.HasPrefix(fn.Name.Name, "Handle") {
					return fmt.Errorf("%s: endpoint must annotate a Controller Handle<Protocol> method", fset.Position(fn.Pos()))
				}
				receiver, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
				if !ok {
					return fmt.Errorf("%s: endpoint needs *Controller receiver", path)
				}
				name, ok := receiver.X.(*ast.Ident)
				if !ok || name.Name != "Controller" {
					return fmt.Errorf("%s: endpoint needs *Controller receiver", path)
				}
				params, err := marker.Endpoint.Parse(rest)
				if err != nil {
					return fmt.Errorf("%s: %w", path, err)
				}
				if params["nest"] == "" {
					return fmt.Errorf("%s: endpoint requires nest=<handler>", path)
				}
				protocolName := strings.TrimPrefix(fn.Name.Name, "Handle")
				domain := filepath.Base(filepath.Dir(path))
				if filepath.Dir(path) != filepath.Join(dir, domain) || file.Name.Name != domain {
					return fmt.Errorf("%s: endpoint must live in game/controllers/<domain> with matching package", path)
				}
				generatedPath := filepath.Join(filepath.Dir(path), toSnake(protocolName)+"_endpoint_gen.go")
				if expected[generatedPath] {
					return fmt.Errorf("%s: duplicate endpoint %s", path, protocolName)
				}
				expected[generatedPath] = true
				plan, err := planProtocolEndpoint(root, manifest, AddOptions{Name: protocolName, Handler: domain, NestHandler: params["nest"]}, true)
				if err != nil {
					return fmt.Errorf("%s: %w", path, err)
				}
				changes = append(changes, plan...)
			}
		}
		if marked != bound {
			return fmt.Errorf("%s: endpoint marker is not attached to a Controller method", path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, path := range owned {
		if expected[path] {
			continue
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		changes = append(changes, syncChange{rel: relativeSlash(root, path), path: path, before: raw, existed: true, remove: true})
	}
	if err := commitSyncChanges(changes); err != nil {
		return err
	}
	for _, change := range changes {
		fmt.Fprintln(stdout, "endpoint:", change.rel)
	}
	return nil
}
