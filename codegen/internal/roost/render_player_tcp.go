type Authenticator interface {
	Authenticate(context.Context, string, net.Addr) (gateway.Principal, error)
}

// RegistryBound is implemented by an Authenticator that needs a capability
// this process publishes — an account client to validate session tickets, a
// key store the verifier reads. Authenticators are built in Init from
// configuration alone; the Mod calls BindRegistry in Provide, after the
// process's Mods have published their capabilities and before the listener
// starts. An error stops the process: a listener whose authenticator cannot
// reach its verifier must not accept connections.
type RegistryBound interface {
	BindRegistry(registry *app.Registry) error
}

type AuthenticatorFunc func(context.Context, string, net.Addr) (gateway.Principal, error)

func (fn AuthenticatorFunc) Authenticate(ctx context.Context, token string, remote net.Addr) (gateway.Principal, error) {
	return fn(ctx, token, remote)
}

type Mod struct {
	config Config
	authenticator Authenticator
	runtime *accessplayer.Runtime
	server *Server
	transportRuntime *Runtime
}

func NewMod() *Mod { return &Mod{} }
func (*Mod) Name() app.ModName { return Name }
func (*Mod) DependsOn() []app.ModName { return []app.ModName{accessplayer.Name} }

func (mod *Mod) Init(cfg *viper.Viper) error {
	parsed, err := configFromViper(cfg)
	if err != nil { return err }
	mod.config = parsed
	if mod.authenticator == nil {
		mod.authenticator, err = newApplicationAuthenticator(cfg)
		if err != nil { return fmt.Errorf("player tcp: initialize authenticator: %%w", err) }
	}
	if mod.authenticator == nil { return errors.New("player tcp: authenticator is nil") }
	return nil
}

func (mod *Mod) Provide(registry *app.Registry) error {
	if registry == nil { return errors.New("player tcp: app registry is nil") }
	runtime, ok := app.Lookup[*accessplayer.Runtime](registry, accessplayer.Name)
	if !ok || runtime == nil || runtime.Protocols == nil { return errors.New("player tcp: player access runtime is unavailable") }
	if bound, ok := mod.authenticator.(RegistryBound); ok {
		if err := bound.BindRegistry(registry); err != nil { return fmt.Errorf("player tcp: bind authenticator: %%w", err) }
	}
	mod.runtime = runtime
	mod.transportRuntime = &Runtime{protocols: runtime.Protocols, loginTimeout: mod.config.LoginTimeout}
	return registry.Register(Name, mod.transportRuntime)
}

func (mod *Mod) Start() error {
	if !mod.config.Enabled {
		slog.Info("player tcp listener disabled")
		return nil
	}
	server, err := NewServer(mod.config, mod.runtime, mod.authenticator)
	if err != nil { return err }
	// Before Start: a close cannot happen until the server accepts, and the
	// link has to be in place by then.
	server.transport = mod.transportRuntime
	if mod.transportRuntime != nil { mod.transportRuntime.startLifecycle() }
	if err := server.Start(); err != nil { return err }
	mod.server = server
	mod.transportRuntime.server.Store(server)
	return nil
}

func (mod *Mod) Stop() {
	ctx, cancel := context.WithTimeout(context.Background(), mod.config.ShutdownTimeout)
	defer cancel()
	_ = mod.StopWithContext(ctx)
}

func (mod *Mod) StopWithContext(ctx context.Context) error {
	if mod.transportRuntime != nil { mod.transportRuntime.server.Store(nil) }
	if mod.server == nil {
		if mod.transportRuntime != nil { mod.transportRuntime.stopLifecycle() }
		return nil
	}
	err := mod.server.Stop(ctx)
	mod.server = nil
	// After the server: the closes it produced on the way down are still
	// worth delivering.
	if mod.transportRuntime != nil { mod.transportRuntime.stopLifecycle() }
	return err
}

// Runtime is the application-facing active publish boundary. It encodes one
// typed protocol value once, then sends it to one session or every currently
// authenticated session of a player. It never exposes socket or Entity state.
type Runtime struct {
	protocols *player_agent.ProtocolRegistry
	server atomic.Pointer[Server]
	loginTimeout time.Duration

	lifecycleMu sync.Mutex
	subscribers map[uint64]func(SessionClosed)
	nextSubscriber uint64
	closedEvents chan SessionClosed
	lifecycleOnce sync.Once
	lifecycleStop chan struct{}
	lifecycleDone chan struct{}
}

// SessionClosed says a connection is gone. It carries identity only: a
// subscriber that needs more looks it up, and a lifecycle event that carried
// state would be a second copy of it.
type SessionClosed struct {
	PlayerID int64
	SessionID string
}

// sessionClosedQueue is how many closes may be in flight before the oldest are
// dropped. Bounded on purpose: a subscriber that blocks must not be able to
// hold the socket cleanup path, and a mass disconnect must not be able to grow
// memory without limit. A dropped event is counted, and every consumer of this
// source has to be able to survive missing one — "who is online" is state that
// is reconciled, not a log that is replayed.
const sessionClosedQueue = 256

// OnSessionClosed subscribes to connection closes and returns the
// unsubscribe. It exists because everything that maintains an "online" set —
// the replicated scene, chat presence — otherwise has to notice by failing to
// push to somebody, which never happens if nothing tries (RR-20260918-06).
//
// Subscribers run on this source's own goroutine, not on the socket's: a slow
// one delays other subscribers and nothing else. Do not block in one.
func (runtime *Runtime) OnSessionClosed(fn func(SessionClosed)) func() {
	if runtime == nil || fn == nil { return func() {} }
	runtime.startLifecycle()
	runtime.lifecycleMu.Lock()
	runtime.nextSubscriber++
	id := runtime.nextSubscriber
	if runtime.subscribers == nil { runtime.subscribers = make(map[uint64]func(SessionClosed)) }
	runtime.subscribers[id] = fn
	runtime.lifecycleMu.Unlock()
	return func() {
		runtime.lifecycleMu.Lock()
		delete(runtime.subscribers, id)
		runtime.lifecycleMu.Unlock()
	}
}

func (runtime *Runtime) startLifecycle() {
	runtime.lifecycleOnce.Do(func() {
		runtime.closedEvents = make(chan SessionClosed, sessionClosedQueue)
		runtime.lifecycleStop = make(chan struct{})
		runtime.lifecycleDone = make(chan struct{})
		go runtime.dispatchClosed()
	})
}

func (runtime *Runtime) dispatchClosed() {
	defer close(runtime.lifecycleDone)
	for {
		select {
		case <-runtime.lifecycleStop:
			// Drain what is already queued: a close that happened before
			// shutdown is still a close, and a subscriber that cleans up
			// external state wants it.
			for {
				select {
				case event := <-runtime.closedEvents:
					runtime.deliverClosed(event)
				default:
					return
				}
			}
		case event := <-runtime.closedEvents:
			runtime.deliverClosed(event)
		}
	}
}

func (runtime *Runtime) deliverClosed(event SessionClosed) {
	type subscriber struct {
		id uint64
		fn func(SessionClosed)
	}
	runtime.lifecycleMu.Lock()
	subscribers := make([]subscriber, 0, len(runtime.subscribers))
	for id, fn := range runtime.subscribers { subscribers = append(subscribers, subscriber{id: id, fn: fn}) }
	runtime.lifecycleMu.Unlock()
	for _, current := range subscribers {
		runtime.callClosedSubscriber(current.id, current.fn, event)
	}
}

// callClosedSubscriber isolates one subscriber. This dispatcher owns a
// goroutine of its own, so a panic nobody recovers here does not fail one
// subscriber — it ends the PROCESS, turning a nil map in a presence bridge
// into an outage for every connected player (RR-20260919-03). Every other
// callback boundary in this framework recovers per callback; so does this one,
// and the subscribers after the failing one still run, because the state they
// maintain — who is online — is exactly what has to converge.
func (runtime *Runtime) callClosedSubscriber(id uint64, fn func(SessionClosed), event SessionClosed) {
	defer func() {
		if recovered := recover(); recovered != nil {
			metrics.IncCounter("player_tcp_session_closed_callback_panics_total", nil, 1)
			slog.Error("player tcp: session-close subscriber panicked",
				"subscriber", id, "player_id", event.PlayerID, "session_id", event.SessionID,
				"panic", recovered, "stack", string(debug.Stack()))
		}
	}()
	fn(event)
}

// publishClosed is called from the socket cleanup path, so it never blocks:
// a full queue drops the event and counts it rather than holding a connection
// teardown behind a subscriber.
func (runtime *Runtime) publishClosed(event SessionClosed) {
	if runtime == nil || runtime.closedEvents == nil { return }
	select {
	case runtime.closedEvents <- event:
	default:
		metrics.IncCounter("player_tcp_session_closed_dropped_total", nil, 1)
	}
}

func (runtime *Runtime) stopLifecycle() {
	if runtime == nil || runtime.lifecycleStop == nil { return }
	select {
	case <-runtime.lifecycleStop:
	default:
		close(runtime.lifecycleStop)
	}
	if runtime.lifecycleDone != nil { <-runtime.lifecycleDone }
}

func (runtime *Runtime) PushPlayer(ctx context.Context, playerID int64, messageID uint32, value any) error {
	if runtime == nil || runtime.protocols == nil { return ErrTransportUnavailable }
	server := runtime.server.Load()
	if server == nil { return ErrTransportUnavailable }
	payload, err := runtime.protocols.Encode(messageID, value)
	if err != nil { return err }
	return server.pushPlayer(ctx, playerID, messageID, payload)
}

func (runtime *Runtime) PushSession(ctx context.Context, sessionID string, messageID uint32, value any) error {
	if runtime == nil || runtime.protocols == nil { return ErrTransportUnavailable }
	server := runtime.server.Load()
	if server == nil { return ErrTransportUnavailable }
	payload, err := runtime.protocols.Encode(messageID, value)
	if err != nil { return err }
	return server.pushSession(ctx, sessionID, messageID, payload)
}

// LoginTimeout is player_access.tcp.login_timeout: how much of a login
// request's dispatch budget the login endpoint gives to taking the player into
// service. Zero means no separate budget (the dispatch deadline still holds).
func (runtime *Runtime) LoginTimeout() time.Duration {
	if runtime == nil { return 0 }
	return runtime.loginTimeout
}

func (runtime *Runtime) ActiveSessions(playerID int64) int {
	if runtime == nil { return 0 }
	server := runtime.server.Load()
	if server == nil { return 0 }
	return server.activeSessions(playerID)
}

// CloseSessions disconnects every session of one player and reports how many
// it closed. It is the transport half of a fail-closed decision: the process
// has concluded it may no longer serve this player, and the honest way to act
// on that is to stop reading their socket rather than to keep accepting work
// it is not entitled to do.
//
// The closes go through the same path a network error takes, so the usual
// lifecycle event reaches every subscriber and the scene, chat presence and
// ownership cleanups run exactly as they would for a disconnect.
func (runtime *Runtime) CloseSessions(playerID int64, reason error) int {
	if runtime == nil { return 0 }
	server := runtime.server.Load()
	if server == nil { return 0 }
	return server.closeSessions(playerID, reason)
}

type Server struct {
	config Config
	runtime *accessplayer.Runtime
	// transport is the application-facing Runtime this server feeds session
	// lifecycle events into. It is set by the Mod before the server starts
	// accepting, and nil in a test that builds a Server directly.
	transport *Runtime
	authenticator Authenticator

	mu sync.RWMutex
	listener net.Listener
	ctx context.Context
	cancel context.CancelFunc
	connections map[net.Conn]struct{}
	ipConnections map[string]int
	sessions map[string]*session
	playerSessions map[int64]map[string]*session
	connectionSlots chan struct{}
	handshakeSlots chan struct{}
	wait sync.WaitGroup
	payloadPool sync.Pool
	stopping bool
	started bool
}

func NewServer(config Config, runtime *accessplayer.Runtime, authenticator Authenticator) (*Server, error) {
	if runtime == nil || runtime.Protocols == nil { return nil, errors.New("player tcp: runtime is nil") }
	if authenticator == nil { return nil, errors.New("player tcp: authenticator is nil") }
	// A Config built before the request budgets existed (RR-20260926-36) has
	// them at zero; it gets the defaults rather than a refusal.
	if config.DispatchTimeout == 0 { config.DispatchTimeout = defaultDispatchTimeout }
	if config.LoginTimeout == 0 { config.LoginTimeout = min(defaultLoginTimeout, config.DispatchTimeout) }
	if err := validateConfig(config); err != nil { return nil, err }
	server := &Server{
		config: config, runtime: runtime, authenticator: authenticator,
		connections: make(map[net.Conn]struct{}),
		ipConnections: make(map[string]int),
		sessions: make(map[string]*session),
		playerSessions: make(map[int64]map[string]*session),
		connectionSlots: make(chan struct{}, config.MaxConnections),
		handshakeSlots: make(chan struct{}, config.MaxHandshakes),
	}
	server.payloadPool.New = func() any { return make([]byte, 4096) }
	return server, nil
}

func (server *Server) Start() error {
	server.mu.Lock()
	defer server.mu.Unlock()
	if server.started { return errors.New("player tcp: server cannot be restarted") }
	listener, err := net.Listen("tcp", server.config.Addr)
	if err != nil { return fmt.Errorf("player tcp: listen %%s: %%w", server.config.Addr, err) }
	server.ctx, server.cancel = context.WithCancel(context.Background())
	server.listener = listener
	server.stopping = false
	server.started = true
	metrics.SetGauge("player_tcp_connections", nil, 0)
	server.wait.Add(1)
	go server.acceptLoop(listener)
	slog.Info("player tcp listener started", "addr", listener.Addr().String(), "max_connections", server.config.MaxConnections)
	return nil
}

func (server *Server) Stop(ctx context.Context) error {
	if ctx == nil { ctx = context.Background() }
	server.mu.Lock()
	listener, cancel := server.listener, server.cancel
	server.listener, server.cancel = nil, nil
	server.stopping = true
	if cancel != nil { cancel() }
	connections := make([]net.Conn, 0, len(server.connections))
	for connection := range server.connections { connections = append(connections, connection) }
	server.mu.Unlock()
	if listener == nil { return nil }
	_ = listener.Close()
	for _, connection := range connections { _ = connection.Close() }
	done := make(chan struct{})
	go func() { server.wait.Wait(); close(done) }()
	select {
	case <-done:
		return nil
	case <-ctx.Done():
		return fmt.Errorf("player tcp: shutdown: %%w", ctx.Err())
	}
}

func (server *Server) acceptLoop(listener net.Listener) {
	defer server.wait.Done()
	backoff := 5 * time.Millisecond
	for {
		connection, err := listener.Accept()
		if err != nil {
			if server.ctx.Err() != nil || errors.Is(err, net.ErrClosed) { return }
			slog.Error("player tcp accept", "err", err)
			timer := time.NewTimer(backoff)
			select {
			case <-server.ctx.Done(): timer.Stop(); return
			case <-timer.C:
			}
			if backoff < time.Second { backoff *= 2 }
			continue
		}
		backoff = 5 * time.Millisecond
		select {
		case server.connectionSlots <- struct{}{}:
			server.mu.Lock()
			if server.stopping || server.ctx.Err() != nil {
				server.mu.Unlock()
				<-server.connectionSlots
				_ = connection.Close()
				return
			}
			host := remoteHost(connection.RemoteAddr())
			if server.ipConnections[host] >= server.config.MaxConnectionsPerIP {
				server.mu.Unlock()
				<-server.connectionSlots
				metrics.IncCounter("player_tcp_connection_rejected_total", map[string]string{"reason": "per_ip"}, 1)
				_ = connection.Close()
				continue
			}
			server.connections[connection] = struct{}{}
			server.ipConnections[host]++
			server.wait.Add(1)
			server.mu.Unlock()
			go server.serveConnection(connection)
		default:
			metrics.IncCounter("player_tcp_connection_rejected_total", nil, 1)
			_ = connection.Close()
		}
	}
}

func (server *Server) serveConnection(connection net.Conn) {
	defer server.wait.Done()
	defer func() { <-server.connectionSlots }()
	metrics.AddGauge("player_tcp_connections", nil, 1)
	defer metrics.AddGauge("player_tcp_connections", nil, -1)
	defer func() {
		server.mu.Lock()
		delete(server.connections, connection)
		host := remoteHost(connection.RemoteAddr())
		if server.ipConnections[host] <= 1 { delete(server.ipConnections, host) } else { server.ipConnections[host]-- }
		server.mu.Unlock()
	}()
	if tcpConnection, ok := connection.(*net.TCPConn); ok {
		_ = tcpConnection.SetKeepAlive(true)
		_ = tcpConnection.SetKeepAlivePeriod(30 * time.Second)
		_ = tcpConnection.SetNoDelay(true)
	}
	// connectionCtx is this connection's lifetime: the server stopping or the
	// session closing (a replacing login, CloseSessions, a network error) ends
	// it, and with it whatever request the connection is still running.
	connectionCtx, cancel := context.WithCancelCause(server.ctx)
	defer cancel(gateway.ErrSessionClosed)
	handshakeCtx, handshakeCancel := context.WithTimeout(connectionCtx, server.config.HandshakeTimeout)
	defer handshakeCancel()
	handshakeDeadline, _ := handshakeCtx.Deadline()
	if err := connection.SetReadDeadline(handshakeDeadline); err != nil { _ = connection.Close(); return }
	select {
	case server.handshakeSlots <- struct{}{}:
	case <-connectionCtx.Done():
		_ = connection.Close(); return
	case <-handshakeCtx.Done():
		metrics.IncCounter("player_tcp_auth_failure_total", map[string]string{"reason": "handshake_capacity"}, 1); _ = connection.Close(); return
	}
	handshakeHeld := true
	defer func() { if handshakeHeld { <-server.handshakeSlots } }()
	authFrame, release, err := server.readFrameLimit(connection, server.config.MaxHandshakeBytes)
	if err != nil { metrics.IncCounter("player_tcp_frame_error_total", nil, 1); _ = connection.Close(); return }
	if authFrame.flags != 0 || authFrame.messageID != 0 || authFrame.sequence == 0 || len(authFrame.payload) == 0 {
		metrics.IncCounter("player_tcp_auth_failure_total", nil, 1); release(); _ = connection.Close(); return
	}
	principal, err := server.authenticator.Authenticate(handshakeCtx, string(authFrame.payload), connection.RemoteAddr())
	handshakeCancel()
	release()
	<-server.handshakeSlots
	handshakeHeld = false
	if err != nil || !principal.Authenticated() { metrics.IncCounter("player_tcp_auth_failure_total", nil, 1); _ = connection.Close(); return }
	session := &session{connection: connection, principal: clonePrincipal(principal), writeTimeout: server.config.WriteTimeout, maxPayloadBytes: server.config.MaxPayloadBytes, cancel: cancel}
	defer func() {
		_ = session.Close(gateway.ErrSessionClosed)
	}()
	if err := session.writeFrame(connectionCtx, 0, 0, authFrame.sequence, nil); err != nil { return }
	server.registerSession(session)
	defer server.unregisterSession(session)
	lastSequence := authFrame.sequence
	for {
		if err := connection.SetReadDeadline(time.Now().Add(server.config.IdleTimeout)); err != nil { return }
		request, releasePayload, err := server.readFrame(connection)
		if err != nil { if !errors.Is(err, io.EOF) { metrics.IncCounter("player_tcp_frame_error_total", nil, 1) }; return }
		if request.flags != 0 || request.messageID == 0 || request.sequence == 0 || int32(request.sequence-lastSequence) <= 0 {
			metrics.IncCounter("player_tcp_frame_error_total", nil, 1); releasePayload(); return
		}
		lastSequence = request.sequence
		// One request, one deadline (RR-20260926-36). Without it a handler
		// waiting on something that never finishes — a cold load behind a
		// projection that keeps failing — held this goroutine, this socket's
		// reads and the connection slot until the process stopped. The read
		// loop is synchronous on purpose (per-connection order, no goroutine
		// per request); the deadline is what keeps that from being unbounded.
		// It bounds waiting, not work: a request the handler already had
		// admitted is not undone by it.
		dispatchStarted := time.Now()
		dispatchCtx, cancelDispatch := context.WithTimeout(connectionCtx, server.config.DispatchTimeout)
		response, dispatchErr := server.runtime.Protocols.Dispatch(dispatchCtx, session, request.messageID, request.sequence, request.payload)
		overBudget := errors.Is(dispatchCtx.Err(), context.DeadlineExceeded)
		cancelDispatch()
		metrics.ObserveDuration("player_tcp_dispatch_duration", nil, time.Since(dispatchStarted))
		releasePayload()
		if overBudget { metrics.IncCounter("player_tcp_dispatch_timeout_total", nil, 1) }
		if dispatchErr != nil {
			metrics.IncCounter("player_tcp_dispatch_error_total", nil, 1)
			slog.Debug("player tcp dispatch failed", "player_id", principal.PlayerID, "message_id", request.messageID, "sequence", request.sequence, "over_budget", overBudget, "err", dispatchErr)
			return
		}
		// The answer goes out on the connection's context, not the request's:
		// a handler that finished at its deadline is reporting what happened,
		// and dropping that report would leave the client guessing.
		if response != nil {
			if err := session.Reply(connectionCtx, response); err != nil { return }
		}
	}
}

func (server *Server) readFrame(reader io.Reader) (frame, func(), error) {
	return server.readFrameLimit(reader, server.config.MaxPayloadBytes)
}

func (server *Server) readFrameLimit(reader io.Reader, maxPayload uint32) (frame, func(), error) {
	var header [headerSize]byte
	if _, err := io.ReadFull(reader, header[:]); err != nil { return frame{}, func(){}, err }
	if header[0] != frameMagic[0] || header[1] != frameMagic[1] || header[2] != protocolVersion || header[3]&^flagServerPush != 0 {
		return frame{}, func(){}, errInvalidFrame
	}
	length := binary.BigEndian.Uint32(header[12:16])
	if length > maxPayload { return frame{}, func(){}, fmt.Errorf("%%w: payload %%d exceeds %%d", errInvalidFrame, length, maxPayload) }
	var payload []byte
	pooled := false
	if length > 0 {
		buffer := server.payloadPool.Get().([]byte)
		if uint32(cap(buffer)) >= length { payload = buffer[:length]; pooled = true } else { payload = make([]byte, length) }
		if _, err := io.ReadFull(reader, payload); err != nil {
			if pooled { server.payloadPool.Put(payload[:cap(payload)]) }
			return frame{}, func(){}, err
		}
	}
	release := func() {
		if pooled && cap(payload) <= maxPooledPayload { server.payloadPool.Put(payload[:cap(payload)]) }
	}
	return frame{flags: header[3], messageID: binary.BigEndian.Uint32(header[4:8]), sequence: binary.BigEndian.Uint32(header[8:12]), payload: payload}, release, nil
}

func (server *Server) registerSession(current *session) {
	server.mu.Lock()
	previous := server.sessions[current.principal.SessionID]
	server.sessions[current.principal.SessionID] = current
	byPlayer := server.playerSessions[current.principal.PlayerID]
	if byPlayer == nil { byPlayer = make(map[string]*session); server.playerSessions[current.principal.PlayerID] = byPlayer }
	byPlayer[current.principal.SessionID] = current
	server.mu.Unlock()
	if previous != nil && previous != current { _ = previous.Close(gateway.ErrSessionClosed) }
}

func (server *Server) unregisterSession(current *session) {
	server.forgetSession(current)
	// The connection is gone; say so once, asynchronously. Everything that
	// maintains an "online" set needs this, and the alternative — noticing by
	// failing to push — never fires if nothing tries (RR-20260918-06).
	if server.transport != nil {
		server.transport.publishClosed(SessionClosed{PlayerID: current.principal.PlayerID, SessionID: current.principal.SessionID})
	}
}

// forgetSession takes a session out of the lookup maps, if it is still the
// one registered under its id. It is the only place that does; the session's
// close event is published by unregisterSession, once, from the connection's
// own teardown.
func (server *Server) forgetSession(current *session) {
	server.mu.Lock()
	if server.sessions[current.principal.SessionID] == current { delete(server.sessions, current.principal.SessionID) }
	if byPlayer := server.playerSessions[current.principal.PlayerID]; byPlayer != nil {
		if byPlayer[current.principal.SessionID] == current { delete(byPlayer, current.principal.SessionID) }
		if len(byPlayer) == 0 { delete(server.playerSessions, current.principal.PlayerID) }
	}
	server.mu.Unlock()
}

// dropBrokenSession closes a connection a push could not be written to
// (RR-20260926-52). It is forgotten first, so the push's caller already sees
// it gone (ActiveSessions, the next push); closing the socket then ends its
// read loop, whose teardown releases the connection slot and the per-IP count
// and publishes the session-close event — the same single release path as any
// other disconnect.
func (server *Server) dropBrokenSession(current *session, cause error) {
	server.forgetSession(current)
	metrics.IncCounter("player_tcp_push_closed_total", nil, 1)
	slog.Debug("player tcp: closing a connection that could not take a push", "player_id", current.principal.PlayerID, "session_id", current.principal.SessionID, "err", cause)
	_ = current.Close(fmt.Errorf("%%w: push not written: %%w", gateway.ErrSessionClosed, cause))
}

// pushPlayer sends one frame to every connection of the player.
//
// A connection the frame could not be written to is closed (dropBrokenSession):
// a partly written frame has put its stream out of step, and a connection that
// cannot take frames — typically the old socket of a player who has logged in
// again — would otherwise stay registered until its read loop notices, failing
// every push meanwhile. The push is then a success if another connection took
// it: the player is reachable, and the closed connection's client has to
// reconnect anyway. It fails when no connection took it (all of them are closed
// by then), and when a connection refused it before writing anything (context
// done, payload too large) — that is not the connection's fault, so nothing is
// closed and the caller learns the frame did not go out everywhere.
func (server *Server) pushPlayer(ctx context.Context, playerID int64, messageID uint32, payload []byte) error {
	if messageID == 0 { return fmt.Errorf("%%w: push message id is zero", errInvalidFrame) }
	server.mu.RLock()
	byPlayer := server.playerSessions[playerID]
	sessions := make([]*session, 0, len(byPlayer))
	for _, current := range byPlayer { sessions = append(sessions, current) }
	server.mu.RUnlock()
	// Counted apart from push errors: a push to a player with no session is the
	// "who is still addressing a gone player" signal, and it used to leave no trace (U-0278).
	if len(sessions) == 0 { metrics.IncCounter("player_tcp_push_no_session_total", nil, 1); return fmt.Errorf("%%w: player %%d", ErrSessionNotFound, playerID) }
	var joined error
	delivered, refused := 0, false
	for _, current := range sessions {
		err := current.push(ctx, messageID, payload)
		switch {
		case err == nil:
			delivered++
			continue
		case errors.Is(err, errConnectionBroken):
			server.dropBrokenSession(current, err)
		default:
			refused = true
		}
		joined = errors.Join(joined, fmt.Errorf("session %%s: %%w", current.principal.SessionID, err))
	}
	if delivered > 0 { metrics.IncCounter("player_tcp_push_total", nil, int64(delivered)) }
	if joined == nil { return nil }
	metrics.IncCounter("player_tcp_push_error_total", nil, 1)
	if delivered > 0 && !refused { return nil }
	return joined
}

func (server *Server) pushSession(ctx context.Context, sessionID string, messageID uint32, payload []byte) error {
	if messageID == 0 { return fmt.Errorf("%%w: push message id is zero", errInvalidFrame) }
	server.mu.RLock()
	current := server.sessions[sessionID]
	server.mu.RUnlock()
	if current == nil { metrics.IncCounter("player_tcp_push_no_session_total", nil, 1); return fmt.Errorf("%%w: %%s", ErrSessionNotFound, sessionID) }
	err := current.push(ctx, messageID, payload)
	if err == nil { metrics.IncCounter("player_tcp_push_total", nil, 1); return nil }
	metrics.IncCounter("player_tcp_push_error_total", nil, 1)
	if errors.Is(err, errConnectionBroken) { server.dropBrokenSession(current, err) }
	return err
}

func (server *Server) activeSessions(playerID int64) int {
	server.mu.RLock()
	defer server.mu.RUnlock()
	return len(server.playerSessions[playerID])
}

// closeSessions snapshots the player's sessions under the lock and closes
// them outside it: Close runs the connection's teardown, which ends up taking
// this same lock to unregister the session.
func (server *Server) closeSessions(playerID int64, reason error) int {
	server.mu.RLock()
	byPlayer := server.playerSessions[playerID]
	targets := make([]*session, 0, len(byPlayer))
	for _, current := range byPlayer {
		targets = append(targets, current)
	}
	server.mu.RUnlock()
	closed := 0
	for _, current := range targets {
		if err := current.Close(reason); err == nil {
			closed++
		}
	}
	return closed
}

type session struct {
	connection net.Conn
	principal gateway.Principal
	writeTimeout time.Duration
	maxPayloadBytes uint32
	writeMu sync.Mutex
	closeOnce sync.Once
	closeErr error
	serverSequence atomic.Uint32
	// cancel ends the connection's context. Close calls it so a session that
	// is closed from outside — replaced by a new login, CloseSessions — stops
	// the request its connection is still running instead of only its socket.
	cancel context.CancelCauseFunc
}

