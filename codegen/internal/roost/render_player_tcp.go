func (session *session) Reply(ctx context.Context, value any) error {
	response, ok := value.(*player_agent.Response)
	if !ok || response == nil { return fmt.Errorf("player tcp: unsupported response %%T", value) }
	if response.MessageID == 0 || response.Sequence == 0 { return fmt.Errorf("%%w: response id and sequence must be non-zero", errInvalidFrame) }
	return session.writeFrame(ctx, 0, response.MessageID, response.Sequence, response.Payload)
}

func (session *session) push(ctx context.Context, messageID uint32, payload []byte) error {
	sequence := session.serverSequence.Add(1)
	if sequence == 0 { sequence = session.serverSequence.Add(1) }
	return session.writeFrame(ctx, flagServerPush, messageID, sequence, payload)
}

func (session *session) writeFrame(ctx context.Context, flags byte, messageID, sequence uint32, payload []byte) error {
	if ctx == nil { ctx = context.Background() }
	if err := ctx.Err(); err != nil { return err }
	limit := session.maxPayloadBytes
	if limit == 0 { limit = hardMaxPayload }
	if uint64(len(payload)) > uint64(limit) { return fmt.Errorf("%%w: outbound payload %%d exceeds %%d", errInvalidFrame, len(payload), limit) }
	session.writeMu.Lock()
	defer session.writeMu.Unlock()
	if session.closeErr != nil { return fmt.Errorf("%%w: %%w", errConnectionBroken, gateway.ErrSessionClosed) }
	// Checked again under the lock: a context that ended while another write
	// held it has written nothing, and must not be mistaken for a write the
	// connection failed (which closes it).
	if err := ctx.Err(); err != nil { return err }
	writeDeadline := time.Now().Add(session.writeTimeout)
	if contextDeadline, ok := ctx.Deadline(); ok && contextDeadline.Before(writeDeadline) { writeDeadline = contextDeadline }
	if err := session.connection.SetWriteDeadline(writeDeadline); err != nil { return fmt.Errorf("%%w: %%w", errConnectionBroken, err) }
	var header [headerSize]byte
	header[0], header[1], header[2] = frameMagic[0], frameMagic[1], protocolVersion
	header[3] = flags
	binary.BigEndian.PutUint32(header[4:8], messageID)
	binary.BigEndian.PutUint32(header[8:12], sequence)
	binary.BigEndian.PutUint32(header[12:16], uint32(len(payload)))
	buffers := net.Buffers{header[:], payload}
	if _, err := buffers.WriteTo(session.connection); err != nil {
		metrics.IncCounter("player_tcp_write_error_total", nil, 1)
		return fmt.Errorf("%%w: %%w", errConnectionBroken, err)
	}
	return nil
}

func remoteHost(address net.Addr) string {
	if address == nil { return "unknown" }
	host, _, err := net.SplitHostPort(address.String())
	if err == nil && host != "" { return host }
	return address.String()
}

func (session *session) Close(reason error) error {
	session.closeOnce.Do(func() {
		if reason == nil { reason = gateway.ErrSessionClosed }
		session.writeMu.Lock()
		session.closeErr = reason
		session.closeErr = errors.Join(reason, session.connection.Close())
		session.writeMu.Unlock()
		if session.cancel != nil { session.cancel(reason) }
	})
	return session.closeErr
}

