// 配置导出的 C# 代码（client_export.config 决定 3）。每张表一个文件，加上读取入口与运行部分：
//
//	csharp/ConfigTables.cs           读取入口 ConfigTables.Load(readText)、DataVersion 常量、ConfigLoadException
//	csharp/ConfigJson.cs             运行部分（client_config_csharp_runtime.go）
//	csharp/ConfigTables.<类型>.cs    普通表：[Serializable] 行类型 <类型> 与表类型 <类型>Table；
//	                                 object / kv：[Serializable] 单例类型 <类型> 与 internal 的 <类型>Reader
//
// 按表拆文件，单个文件不随表数变大，改一张表只动它自己的文件。生成代码里引用生成的类型一律写 global::<命名空间>.<类型>，
// 避免与表名、字段名同名的成员遮住类型。

const configCSharpHeader = `// <auto-generated>
// Code generated by roost client_export.config. DO NOT EDIT.
// 来源：服务端工程的 configs/schema 与 configs/table（roost generate）；只含客户端字段。
// </auto-generated>
#nullable disable
`

// configCSharpFixedTypes 是生成代码里固定的类型名；表的类型名不能与它们相同。
var configCSharpFixedTypes = []string{"ConfigTables", "ConfigLoadException", "ConfigJson", "ConfigJsonNode", "ConfigJsonKind", "ConfigJsonParser", "ConfigRule", "ConfigSite"}

// configTablesMembers 是 ConfigTables 自己的成员名（含继承自 object 的）；表的属性以类型名命名，不能与它们相同。
var configTablesMembers = []string{"DataVersion", "ShortDataVersion", "Load", "DataFiles", "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "ReferenceEquals", "Finalize"}

// csharpKeywords 是 C# 的保留关键字：与它们同名的字段写成 @名字（元数据里的名字不变，仍与 JSON 键一致）。
var csharpKeywords = map[string]bool{}

func init() {
	for _, word := range strings.Fields(`abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while`) {
		csharpKeywords[word] = true
	}
}

var csharpIdentifier = regexp.MustCompile(`^[\p{L}_][\p{L}\p{Nd}_]*$`)

// csType 是一个字段在 C# 里的类型与读法。
type csType struct {
	decl string // C# 类型表达式
	// read 生成读取调用：node、site 是 C# 表达式，depth 用来给嵌套 lambda 的参数取不重名的名字。
	read func(node, site string, depth int) string
	// scalar 是标量的种类（signed / unsigned / float / string / bool），用于主键、index 与 ref；复合类型为空。
	scalar string
	// nullable 表示 Go 里是指针（*T）：缺省或 null 为 null。
	nullable bool
	// method 是标量在 ConfigJson 里的读取方法名（ReadInt32 等），只有标量有。
	method string
}

// fn 把读法写成 Func<ConfigJsonNode, ConfigSite, T>，供数组、字典、可空类型的元素用。
func (t csType) fn(depth int) string {
	node, site := fmt.Sprintf("n%d", depth), fmt.Sprintf("s%d", depth)
	return fmt.Sprintf("(%s, %s) => %s", node, site, t.read(node, site, depth+1))
}

func scalarCS(decl, reader, kind string) csType {
	return csType{decl: decl, scalar: kind, method: reader, read: func(node, site string, _ int) string {
		return fmt.Sprintf("ConfigJson.%s(%s, %s)", reader, node, site)
	}}
}

var csScalars = map[string]csType{
	"string":  scalarCS("string", "ReadString", "string"),
	"bool":    scalarCS("bool", "ReadBool", "bool"),
	"int8":    scalarCS("sbyte", "ReadInt8", "signed"),
	"int16":   scalarCS("short", "ReadInt16", "signed"),
	"int32":   scalarCS("int", "ReadInt32", "signed"),
	"rune":    scalarCS("int", "ReadInt32", "signed"),
	"int":     scalarCS("long", "ReadInt64", "signed"),
	"int64":   scalarCS("long", "ReadInt64", "signed"),
	"uint8":   scalarCS("byte", "ReadUInt8", "unsigned"),
	"byte":    scalarCS("byte", "ReadUInt8", "unsigned"),
	"uint16":  scalarCS("ushort", "ReadUInt16", "unsigned"),
	"uint32":  scalarCS("uint", "ReadUInt32", "unsigned"),
	"uint":    scalarCS("ulong", "ReadUInt64", "unsigned"),
	"uint64":  scalarCS("ulong", "ReadUInt64", "unsigned"),
	"float32": scalarCS("float", "ReadFloat32", "float"),
	"float64": scalarCS("double", "ReadFloat64", "float"),
}

// csharpType 把 schema 里的 Go 类型表达式换成 C# 类型。支持内建标量、指向标量的指针、切片（[]byte 除外）与
// map[string]T，可以嵌套；带解析器（parser）的字段一律是 string（客户端拿到 CSV 原文，自己解析）。
// 别的类型（具名类型、结构体、time.Duration 等）生成器不知道它的 JSON 形状，报错。
func csharpType(goType string, parser bool) (csType, error) {
	if parser {
		return csScalars["string"], nil
	}
	return csharpTypeOf(strings.TrimSpace(goType))
}

func csharpTypeOf(goType string) (csType, error) {
	if scalar, ok := csScalars[goType]; ok {
		return scalar, nil
	}
	switch {
	case strings.HasPrefix(goType, "*"):
		inner, ok := csScalars[strings.TrimPrefix(goType, "*")]
		if !ok {
			return csType{}, fmt.Errorf("type %s: only pointers to built-in scalars are supported", goType)
		}
		if inner.scalar == "string" {
			return csType{decl: "string", scalar: "string", nullable: true, read: func(node, site string, _ int) string {
				return fmt.Sprintf("ConfigJson.ReadNullableString(%s, %s)", node, site)
			}}, nil
		}
		return csType{decl: inner.decl + "?", scalar: inner.scalar, nullable: true, read: func(node, site string, _ int) string {
			return fmt.Sprintf("ConfigJson.ReadNullable<%s>(%s, %s, ConfigJson.%s)", inner.decl, node, site, inner.method)
		}}, nil
	case goType == "[]byte" || goType == "[]uint8":
		return csType{}, fmt.Errorf("type %s: encoding/json writes []byte as base64; declare []int32 or a string", goType)
	case strings.HasPrefix(goType, "[]"):
		elem, err := csharpTypeOf(strings.TrimPrefix(goType, "[]"))
		if err != nil {
			return csType{}, err
		}
		return csType{decl: elem.decl + "[]", read: func(node, site string, depth int) string {
			return fmt.Sprintf("ConfigJson.ReadArray<%s>(%s, %s, %s)", elem.decl, node, site, elem.fn(depth))
		}}, nil
	case strings.HasPrefix(goType, "map[string]"):
		elem, err := csharpTypeOf(strings.TrimPrefix(goType, "map[string]"))
		if err != nil {
			return csType{}, err
		}
		return csType{decl: "global::System.Collections.Generic.Dictionary<string, " + elem.decl + ">", read: func(node, site string, depth int) string {
			return fmt.Sprintf("ConfigJson.ReadMap<%s>(%s, %s, %s)", elem.decl, node, site, elem.fn(depth))
		}}, nil
	case strings.HasPrefix(goType, "map["):
		return csType{}, fmt.Errorf("type %s: only map[string]T is supported (JSON object keys are strings)", goType)
	}
	return csType{}, fmt.Errorf("type %s is not supported in the client export (built-in scalars, pointers to them, slices and map[string]T are); give the field parser:\"...\" so the client gets the raw string, or side:\"s\"", goType)
}

// canonicalCS 生成标量值的规范字符串（与 ConfigJson.Canonical 对 JSON 值的结果一致），用于主键点名与 ref 查找。
func canonicalCS(kind, value string) string {
	switch kind {
	case "signed":
		return "ConfigJson.CanonicalInt((long)" + value + ")"
	case "unsigned":
		return "ConfigJson.CanonicalUInt((ulong)" + value + ")"
	case "float":
		return "ConfigJson.CanonicalFloat((double)" + value + ")"
	case "bool":
		return "(" + value + " ? \"true\" : \"false\")"
	}
	return value
}

// zeroCS 生成“值是零值”的判断（ref 的零值表示没有引用，Required 时零值也要查）。
func zeroCS(kind, value string) string {
	switch kind {
	case "string":
		return "string.IsNullOrEmpty(" + value + ")"
	case "bool":
		return "!" + value
	}
	return value + " == 0"
}

// csString 写一个 C# 字符串字面量。
func csString(value string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range value {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f || r == 0x85 || r == 0x2028 || r == 0x2029:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// xmlDoc 把说明文字写成一行 XML 文档注释的内容。
func xmlDoc(text string) string {
	text = strings.Join(strings.Fields(text), " ")
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(text)
}

func csIdentifier(name string) string {
	if csharpKeywords[name] {
		return "@" + name
	}
	return name
}

// csField 是一个字段渲染时要的全部信息。
type csField struct {
	export tablegen.ExportField
	ident  string
	typ    csType
}

// csTable 是一张表渲染时要的全部信息。
type csTable struct {
	export tablegen.ExportTable
	fields []csField
	key    *csField
	byJSON map[string]*csField
	// refTypes 是 ref 目标表名 → 目标的类型名。
	refTypes map[string]string
}

func (t *csTable) single() bool { return t.export.Kind != tablegen.KindTable }

func prepareConfigTables(tables []tablegen.ExportTable) ([]*csTable, error) {
	types := map[string]string{}
	for _, name := range configCSharpFixedTypes {
		types[name] = "a generated runtime type"
	}
	claim := func(typeName, owner string) error {
		if other, taken := types[typeName]; taken {
			return fmt.Errorf("C# type name %s of %s collides with %s; rename the schema struct", typeName, owner, other)
		}
		types[typeName] = owner
		return nil
	}
	var out []*csTable
	for _, table := range tables {
		owner := "table " + table.Name
		if !csharpIdentifier.MatchString(table.TypeName) {
			return nil, fmt.Errorf("%s: type name %q is not a C# identifier", owner, table.TypeName)
		}
		for _, member := range configTablesMembers {
			if table.TypeName == member {
				return nil, fmt.Errorf("%s: type name %s is a member of ConfigTables; rename the schema struct", owner, table.TypeName)
			}
		}
		if err := claim(table.TypeName, owner); err != nil {
			return nil, err
		}
		helper := table.TypeName + "Reader"
		if table.Kind == tablegen.KindTable {
			helper = table.TypeName + "Table"
		}
		if err := claim(helper, owner); err != nil {
			return nil, err
		}
		item := &csTable{export: table, byJSON: map[string]*csField{}, refTypes: map[string]string{}}
		for _, field := range table.Fields {
			where := fmt.Sprintf("%s field %s", owner, field.Name)
			if !csharpIdentifier.MatchString(field.JSON) {
				return nil, fmt.Errorf("%s: JSON name %q is not a C# identifier, so the row type cannot carry it as a field", where, field.JSON)
			}
			if field.JSON == table.TypeName {
				return nil, fmt.Errorf("%s: JSON name %q equals the type name; C# forbids a member named like its type", where, field.JSON)
			}
			typ, err := csharpType(field.Type, field.Parser != "")
			if err != nil {
				return nil, fmt.Errorf("%s: %w", where, err)
			}
			item.fields = append(item.fields, csField{export: field, ident: csIdentifier(field.JSON), typ: typ})
		}
		for i := range item.fields {
			field := &item.fields[i]
			item.byJSON[field.export.JSON] = field
			if field.export.Key {
				if field.typ.scalar == "" || field.typ.nullable || field.typ.scalar == "float" {
					return nil, fmt.Errorf("%s: key field %s has type %s; the client export supports string, integer and bool keys", owner, field.export.Name, field.export.Type)
				}
				item.key = field
			}
			if field.export.Index != "" && (field.typ.scalar == "" || field.typ.nullable) {
				return nil, fmt.Errorf("%s: index %s on field %s of type %s is not supported in the client export", owner, field.export.Index, field.export.Name, field.export.Type)
			}
		}
		if table.Kind == tablegen.KindTable && item.key == nil {
			return nil, fmt.Errorf("%s has no key field", owner)
		}
		out = append(out, item)
	}
	// ref 的目标必须也导出（tables 选表时可能被排除），字段是能当主键比较的标量。
	byName := map[string]*csTable{}
	for _, table := range out {
		byName[table.export.Name] = table
	}
	for _, table := range out {
		for _, rule := range table.export.Rules {
			if rule.Ref == "" {
				continue
			}
			target, ok := byName[rule.Ref]
			if !ok {
				return nil, fmt.Errorf("table %s field %s refs table %s, which is not exported; add it to client_export.config.tables", table.export.Name, rule.Field, rule.Ref)
			}
			if target.single() {
				return nil, fmt.Errorf("table %s field %s refs %s, which is not a keyed table", table.export.Name, rule.Field, rule.Ref)
			}
			field := table.byJSON[rule.Field]
			if field == nil || field.typ.scalar == "" || field.typ.scalar == "float" {
				return nil, fmt.Errorf("table %s field %s: ref needs a string, integer or bool field", table.export.Name, rule.Field)
			}
			table.refTypes[rule.Ref] = target.export.TypeName
		}
	}
	return out, nil
}

// renderConfigCSharp 渲染配置导出的全部 C# 文件（文件名 → 内容）。tables 已按表名排序。
func renderConfigCSharp(tables []tablegen.ExportTable, namespace, version string) (map[string][]byte, error) {
	prepared, err := prepareConfigTables(tables)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{
		"ConfigJson.cs":   []byte(strings.ReplaceAll(configCSharpRuntime, "@NAMESPACE@", namespace)),
		"ConfigTables.cs": renderConfigTablesEntry(prepared, namespace, version),
	}
	for _, table := range prepared {
		var b strings.Builder
		b.WriteString(configCSharpHeader)
		fmt.Fprintf(&b, "\nnamespace %s\n{\n", namespace)
		if table.single() {
			renderConfigSingle(&b, table, namespace)
		} else {
			renderConfigTable(&b, table, namespace)
		}
		b.WriteString("}\n")
		files["ConfigTables."+table.export.TypeName+".cs"] = []byte(b.String())
	}
	return files, nil
}

func renderConfigTablesEntry(tables []*csTable, namespace, version string) []byte {
	g := "global::" + namespace + "."
	var b strings.Builder
	b.WriteString(configCSharpHeader)
	fmt.Fprintf(&b, `
namespace %[1]s
{
    /// <summary>加载配置表失败：哪张表、哪一行（1 起；单例为 0）、该行主键、哪个字段、哪条规则（hash / json / shape / type / required / unique / min / enum / ref / read）。</summary>
    public sealed class ConfigLoadException : global::System.Exception
    {
        /// <summary>表名。</summary>
        public string Table { get; }
        /// <summary>行号（1 起，数据文件里 rows 的顺序）；单例或整个文件的问题为 0。</summary>
        public int Row { get; }
        /// <summary>该行主键的规范形式；不知道时为 null。</summary>
        public string Key { get; }
        /// <summary>字段的 JSON 名（数组元素写成 field[i]，字典项写成 field.key）；整张表的问题为 null。</summary>
        public string Field { get; }
        /// <summary>违反的规则：hash / read / json / shape / type / required / unique / min / enum / ref。</summary>
        public string Rule { get; }
        /// <summary>说明。</summary>
        public string Detail { get; }

        /// <summary>点名一次加载失败。</summary>
        public ConfigLoadException(string table, int row, string key, string field, string rule, string detail)
            : this(table, row, key, field, rule, detail, null)
        {
        }

        /// <summary>点名一次加载失败，并带上原因。</summary>
        public ConfigLoadException(string table, int row, string key, string field, string rule, string detail, global::System.Exception inner)
            : base(Format(table, row, key, field, rule, detail), inner)
        {
            Table = table;
            Row = row;
            Key = key;
            Field = field;
            Rule = rule;
            Detail = detail;
        }

        static string Format(string table, int row, string key, string field, string rule, string detail)
        {
            var b = new global::System.Text.StringBuilder();
            b.Append("table ").Append(table);
            if (row > 0)
            {
                b.Append(" row ").Append(row.ToString(global::System.Globalization.CultureInfo.InvariantCulture));
                if (!string.IsNullOrEmpty(key))
                {
                    b.Append(" (key ").Append(key).Append(')');
                }
            }
            if (!string.IsNullOrEmpty(field))
            {
                b.Append(" field ").Append(field);
            }
            b.Append(": ").Append(rule).Append(": ").Append(detail);
            return b.ToString();
        }
    }

    /// <summary>
    /// 导出给客户端的配置表（只含客户端字段）。用 Load 读出一个实例，由调用方持有；没有静态的可变状态，两次 Load 得到两个互不相干的实例。
    /// 带解析器（parser）的字段在这里是 CSV 原文字符串，由游戏自己解析。没有运行时版本核对：DataVersion 只供显示或上报。
    /// </summary>
    public sealed class ConfigTables
    {
        /// <summary>数据版本：导出表的数据哈希按表名排序后合起来的 sha256（与服务端 shared/config/manifest.json 的 data_version 相同）。</summary>
        public const string DataVersion = %[2]s;

        /// <summary>DataVersion 的前 12 位，供显示。</summary>
        public const string ShortDataVersion = %[3]s;
`, namespace, csString(version), csString(shortVersion(version)))
	for _, table := range tables {
		typeName := g + table.export.TypeName
		if !table.single() {
			typeName += "Table"
		}
		fmt.Fprintf(&b, "\n        /// <summary>配置表 %s。</summary>\n        public %s %s { get; }\n", xmlDoc(table.export.Name), typeName, table.export.TypeName)
	}
	b.WriteString("\n        ConfigTables(")
	for i, table := range tables {
		if i > 0 {
			b.WriteString(", ")
		}
		typeName := g + table.export.TypeName
		if !table.single() {
			typeName += "Table"
		}
		fmt.Fprintf(&b, "%s p%d", typeName, i)
	}
	b.WriteString(")\n        {\n")
	for i, table := range tables {
		fmt.Fprintf(&b, "            %s = p%d;\n", table.export.TypeName, i)
	}
	b.WriteString("        }\n\n")
	b.WriteString("        /// <summary>导出的数据文件名（Load 传给 readText 的参数），按表名排序。每次返回新数组。</summary>\n")
	b.WriteString("        public static string[] DataFiles()\n        {\n            return new string[] {")
	for i, table := range tables {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(&b, " %s", csString(table.export.Name+".json"))
	}
	b.WriteString(" };\n        }\n\n")
	fmt.Fprintf(&b, `        /// <summary>
        /// 读出全部配置表。readText 收到数据文件名（如 "monster.json"，见 DataFiles），返回文件内容；读文件的方式（Resources、
        /// Addressables、StreamingAssets）由调用方决定。先核对每个文件的数据哈希与导出清单一致（CRLF 统一成 LF 再算），
        /// 不一致抛出带表名的 ConfigLoadException；再按服务端声明的规则检查 required、unique、min、enum、ref，违反时写明表、行和字段。
        /// </summary>
        public static %[1]sConfigTables Load(global::System.Func<string, string> readText)
        {
            if (readText == null)
            {
                throw new global::System.ArgumentNullException(nameof(readText));
            }
`, g)
	for i, table := range tables {
		fmt.Fprintf(&b, "            string text%d = %sConfigJson.ReadVerified(readText, %s, %s, %s);\n", i, g, csString(table.export.Name), csString(table.export.Name+".json"), csString(table.export.DataHash))
	}
	for i, table := range tables {
		helper := g + table.export.TypeName + "Reader"
		if !table.single() {
			helper = g + table.export.TypeName + "Table"
		}
		fmt.Fprintf(&b, "            var t%d = %s.Parse(text%d);\n", i, helper, i)
	}
	index := map[string]int{}
	for i, table := range tables {
		index[table.export.Name] = i
	}
	for i, table := range tables {
		targets := refTargets(table)
		if len(targets) == 0 {
			continue
		}
		args := make([]string, len(targets))
		for j, target := range targets {
			args[j] = fmt.Sprintf("t%d", index[target])
		}
		fmt.Fprintf(&b, "            t%d.CheckRefs(%s);\n", i, strings.Join(args, ", "))
	}
	b.WriteString("            return new " + g + "ConfigTables(")
	for i := range tables {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "t%d", i)
	}
	b.WriteString(");\n        }\n    }\n}\n")
	return []byte(b.String())
}

// refTargets 是一张表 ref 到的表（去重、按第一次出现的顺序）。
func refTargets(table *csTable) []string {
	var targets []string
	seen := map[string]bool{}
	for _, rule := range table.export.Rules {
		if rule.Ref != "" && !seen[rule.Ref] {
			seen[rule.Ref] = true
			targets = append(targets, rule.Ref)
		}
	}
	return targets
}

func renderRules(b *strings.Builder, declared []rules.Rule) {
	b.WriteString("            return new ConfigRule[]\n            {\n")
	for _, rule := range declared {
		if !rule.Required && !rule.Unique && rule.Min == "" && len(rule.Enum) == 0 {
			continue // 只有 ref 的规则在 CheckRefs 里查
		}
		minimum := "null"
		if rule.Min != "" {
			minimum = csString(rule.Min)
		}
		enum := "null"
		if len(rule.Enum) > 0 {
			values := make([]string, len(rule.Enum))
			for i, value := range rule.Enum {
				values[i] = csString(value)
			}
			enum = "new string[] { " + strings.Join(values, ", ") + " }"
		}
		fmt.Fprintf(b, "                new ConfigRule(%s, %t, %t, %s, %s),\n", csString(rule.Field), rule.Required, rule.Unique, minimum, enum)
	}
	b.WriteString("            };\n")
}

// fieldDoc 是字段的文档注释：kv 表用 note 列，别的表用 title，都没有时用 JSON 名；带解析器的字段注明是原文字符串。
func fieldDoc(field tablegen.ExportField) string {
	doc := field.JSON
	if field.Note != "" {
		doc = field.Note
	} else if field.Title != "" {
		doc = field.Title
	}
	if field.Parser != "" {
		doc += fmt.Sprintf("（parser %s：CSV 原文字符串，由游戏自己解析）", field.Parser)
	}
	return xmlDoc(doc)
}

func renderRowFields(b *strings.Builder, table *csTable) {
	for _, field := range table.fields {
		fmt.Fprintf(b, "        /// <summary>%s</summary>\n", fieldDoc(field.export))
		fmt.Fprintf(b, "        public %s %s;\n", field.typ.decl, field.ident)
	}
}

func renderReadFields(b *strings.Builder, table *csTable, node, row, indent string) {
	for _, field := range table.fields {
		fmt.Fprintf(b, "%s%s.%s = %s;\n", indent, row, field.ident,
			field.typ.read(fmt.Sprintf("%s.Get(%s)", node, csString(field.export.JSON)), fmt.Sprintf("site.At(%s)", csString(field.export.JSON)), 1))
	}
}

func renderConfigSingle(b *strings.Builder, table *csTable, namespace string) {
	g := "global::" + namespace + "."
	t := table.export
	layout := "横排 object，一行"
	if t.Kind == tablegen.KindKV {
		layout = "竖排键值表（key,value,note）"
	}
	fmt.Fprintf(b, "    /// <summary>配置 %s（configs/table/%s，%s；只含客户端字段）。</summary>\n", xmlDoc(t.Name), xmlDoc(t.File), layout)
	fmt.Fprintf(b, "    [global::System.Serializable]\n    public sealed class %s\n    {\n", t.TypeName)
	renderRowFields(b, table)
	b.WriteString("    }\n\n")
	fmt.Fprintf(b, `    internal static class %[1]sReader
    {
        internal const string Name = %[2]s;

        internal static %[3]s%[1]s Parse(string text)
        {
            var node = ConfigJson.Single(ConfigJsonParser.Parse(text, Name), Name);
            ConfigJson.CheckRules(Name, new global::System.Collections.Generic.List<ConfigJsonNode> { node }, Rules(), null, true);
            var site = new ConfigSite(Name, 0, null, null);
            var row = new %[3]s%[1]s();
`, t.TypeName, csString(t.Name), g)
	renderReadFields(b, table, "node", "row", "            ")
	b.WriteString("            return row;\n        }\n\n        static ConfigRule[] Rules()\n        {\n")
	renderRules(b, t.Rules)
	b.WriteString("        }\n    }\n")
}

func renderConfigTable(b *strings.Builder, table *csTable, namespace string) {
	g := "global::" + namespace + "."
	t := table.export
	row := g + t.TypeName
	key := table.key
	keyDecl := key.typ.decl
	keyComparer := ""
	if key.typ.scalar == "string" {
		keyComparer = "global::System.StringComparer.Ordinal"
	}
	fmt.Fprintf(b, "    /// <summary>配置表 %s 的一行（configs/table/%s；只含客户端字段）。</summary>\n", xmlDoc(t.Name), xmlDoc(t.File))
	fmt.Fprintf(b, "    [global::System.Serializable]\n    public sealed class %s\n    {\n", t.TypeName)
	renderRowFields(b, table)
	b.WriteString("    }\n\n")
	fmt.Fprintf(b, "    /// <summary>配置表 %s（主键 %s）。由 ConfigTables.Load 读出，只读使用。</summary>\n", xmlDoc(t.Name), xmlDoc(key.export.JSON))
	fmt.Fprintf(b, "    public sealed class %sTable\n    {\n", t.TypeName)
	fmt.Fprintf(b, "        /// <summary>表名。</summary>\n        public const string Name = %s;\n\n", csString(t.Name))
	fmt.Fprintf(b, "        readonly %s[] rows;\n", row)
	fmt.Fprintf(b, "        readonly global::System.Collections.Generic.Dictionary<%s, %s> byKey;\n", keyDecl, row)
	b.WriteString("        readonly string[] keyTexts;\n")
	b.WriteString("        readonly global::System.Collections.Generic.HashSet<string> keySet;\n")
	var indexed []csField
	for _, field := range table.fields {
		if field.export.Index != "" {
			indexed = append(indexed, field)
		}
	}
	for i, field := range indexed {
		fmt.Fprintf(b, "        readonly global::System.Collections.Generic.Dictionary<%s, %s[]> index%d;\n", field.typ.decl, row, i)
	}
	fmt.Fprintf(b, "\n        %sTable(%s[] rows)\n        {\n            this.rows = rows;\n", t.TypeName, row)
	fmt.Fprintf(b, "            byKey = new global::System.Collections.Generic.Dictionary<%s, %s>(%s);\n", keyDecl, row, keyComparer)
	b.WriteString("            keyTexts = new string[rows.Length];\n")
	b.WriteString("            keySet = new global::System.Collections.Generic.HashSet<string>(global::System.StringComparer.Ordinal);\n")
	for i, field := range indexed {
		comparer := ""
		if field.typ.scalar == "string" {
			comparer = "global::System.StringComparer.Ordinal"
		}
		fmt.Fprintf(b, "            var lists%d = new global::System.Collections.Generic.Dictionary<%s, global::System.Collections.Generic.List<%s>>(%s);\n", i, field.typ.decl, row, comparer)
	}
	b.WriteString("            for (int i = 0; i < rows.Length; i++)\n            {\n                var row = rows[i];\n")
	fmt.Fprintf(b, "                byKey.Add(row.%s, row);\n", key.ident)
	fmt.Fprintf(b, "                keyTexts[i] = %s;\n                keySet.Add(keyTexts[i]);\n", canonicalCS(key.typ.scalar, "row."+key.ident))
	for i, field := range indexed {
		fmt.Fprintf(b, `                global::System.Collections.Generic.List<%[1]s> list%[2]d;
                if (!lists%[2]d.TryGetValue(row.%[3]s, out list%[2]d))
                {
                    list%[2]d = new global::System.Collections.Generic.List<%[1]s>();
                    lists%[2]d.Add(row.%[3]s, list%[2]d);
                }
                list%[2]d.Add(row);
`, row, i, field.ident)
	}
	b.WriteString("            }\n")
	for i, field := range indexed {
		comparer := ""
		if field.typ.scalar == "string" {
			comparer = "global::System.StringComparer.Ordinal"
		}
		fmt.Fprintf(b, "            index%[1]d = new global::System.Collections.Generic.Dictionary<%[2]s, %[3]s[]>(%[4]s);\n", i, field.typ.decl, row, comparer)
		fmt.Fprintf(b, "            foreach (var entry in lists%[1]d)\n            {\n                index%[1]d.Add(entry.Key, entry.Value.ToArray());\n            }\n", i)
	}
	b.WriteString("        }\n\n")
	fmt.Fprintf(b, `        /// <summary>全部行，按数据文件里的顺序。</summary>
        public global::System.Collections.Generic.IReadOnlyList<%[1]s> All
        {
            get { return rows; }
        }

        /// <summary>行数。</summary>
        public int Count
        {
            get { return rows.Length; }
        }

        /// <summary>按主键 %[3]s 取一行；没有时抛出 KeyNotFoundException。</summary>
        public %[1]s Get(%[2]s key)
        {
            %[1]s row;
            if (!byKey.TryGetValue(key, out row))
            {
                throw new global::System.Collections.Generic.KeyNotFoundException("config table " + Name + " has no row with key " + key);
            }
            return row;
        }

        /// <summary>按主键 %[3]s 取一行。</summary>
        public bool TryGet(%[2]s key, out %[1]s row)
        {
            return byKey.TryGetValue(key, out row);
        }
`, row, keyDecl, xmlDoc(key.export.JSON))
	for i, field := range indexed {
		fmt.Fprintf(b, `
        /// <summary>按 index %[4]s（字段 %[5]s）查全部匹配的行，按文件顺序；没有时返回空列表。</summary>
        public global::System.Collections.Generic.IReadOnlyList<%[1]s> By%[4]s(%[2]s value)
        {
            %[1]s[] found;
            return index%[3]d.TryGetValue(value, out found) ? found : global::System.Array.Empty<%[1]s>();
        }
`, row, field.typ.decl, i, field.export.Index, xmlDoc(field.export.JSON))
	}
	fmt.Fprintf(b, `
        internal bool HasKey(string canonical)
        {
            return keySet.Contains(canonical);
        }

        internal static %[1]sTable Parse(string text)
        {
            var nodes = ConfigJson.Rows(ConfigJsonParser.Parse(text, Name), Name);
            ConfigJson.CheckRules(Name, nodes, Rules(), %[2]s, false);
            var rows = new %[3]s[nodes.Count];
            for (int i = 0; i < rows.Length; i++)
            {
                var node = nodes[i];
                var site = new ConfigSite(Name, i + 1, ConfigJson.KeyOf(node, %[2]s), null);
                var row = new %[3]s();
`, g+t.TypeName, csString(key.export.JSON), row)
	renderReadFields(b, table, "node", "row", "                ")
	b.WriteString("                rows[i] = row;\n            }\n")
	fmt.Fprintf(b, "            return new %sTable(rows);\n        }\n\n        static ConfigRule[] Rules()\n        {\n", g+t.TypeName)
	renderRules(b, t.Rules)
	b.WriteString("        }\n")
	renderRefs(b, table, namespace)
	b.WriteString("    }\n")
}

// renderRefs 生成 CheckRefs：全部表读完后检查 ref，语义同服务端 configdata：零值（指针为 null）表示没有引用，
// Required 时零值也要指向存在的主键。
func renderRefs(b *strings.Builder, table *csTable, namespace string) {
	targets := refTargets(table)
	if len(targets) == 0 {
		return
	}
	g := "global::" + namespace + "."
	params := make([]string, len(targets))
	param := map[string]string{}
	for i, target := range targets {
		param[target] = fmt.Sprintf("target%d", i)
		params[i] = fmt.Sprintf("%s%sTable %s", g, table.refTypes[target], param[target])
	}
	fmt.Fprintf(b, "\n        internal void CheckRefs(%s)\n        {\n            for (int i = 0; i < rows.Length; i++)\n            {\n                var row = rows[i];\n", strings.Join(params, ", "))
	for _, rule := range table.export.Rules {
		if rule.Ref == "" {
			continue
		}
		field := table.byJSON[rule.Field]
		value := "row." + field.ident
		indent := "                "
		if field.typ.nullable && field.typ.scalar != "string" {
			fmt.Fprintf(b, "%sif (%s.HasValue)\n%s{\n", indent, value, indent)
			value += ".Value"
			indent += "    "
		} else if field.typ.nullable {
			fmt.Fprintf(b, "%sif (%s != null)\n%s{\n", indent, value, indent)
			indent += "    "
		}
		condition := fmt.Sprintf("!%s.HasKey(%s)", param[rule.Ref], canonicalCS(field.typ.scalar, value))
		if !rule.Required {
			condition = fmt.Sprintf("!(%s) && %s", zeroCS(field.typ.scalar, value), condition)
		}
		fmt.Fprintf(b, "%sif (%s)\n%s{\n", indent, condition, indent)
		fmt.Fprintf(b, "%s    throw new ConfigLoadException(Name, i + 1, keyTexts[i], %s, \"ref\", \"references missing %s key \" + %s);\n",
			indent, csString(rule.Field), strings.ReplaceAll(rule.Ref, `"`, ``), canonicalCS(field.typ.scalar, value))
		fmt.Fprintf(b, "%s}\n", indent)
		if field.typ.nullable {
			fmt.Fprintf(b, "                }\n")
		}
	}
	b.WriteString("            }\n        }\n")
}
