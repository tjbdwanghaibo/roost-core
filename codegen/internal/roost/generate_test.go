	before := snapshotTree(t, root)
	var preview bytes.Buffer
	if err := Run([]string{"project", "upgrade", "--root", root, "--dry-run", "-core", "latest"}, &preview, io.Discard); err != nil {
		t.Fatalf("upgrade --dry-run: %v", err)
	}
