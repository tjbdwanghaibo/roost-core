func TestTemplateFailureDoesNotPublishPartialProject(t *testing.T) {
	parent := t.TempDir()
	target := filepath.Join(parent, "b7")
	syncProjectBeforeCommit = func() {
		root := target
		if _, err := os.Stat(root); os.IsNotExist(err) {
			stages, err := filepath.Glob(filepath.Join(parent, ".roost-project-*"))
			if err != nil || len(stages) != 1 {
				t.Fatalf("stage: %v %v", stages, err)
			}
			root = stages[0]
		}
		rel := "configs/service/config.game.yaml"
		body := readProjectFile(t, root, rel)
		writeProjectFile(t, root, rel, body+"\n# injected concurrent template edit\n")
	}
	defer func() { syncProjectBeforeCommit = nil }()
	_, _, err := NewProject(NewOptions{Name: "b7", Module: "example.com/b7", Out: target, Template: "game-demo"})
	if err == nil || !strings.Contains(err.Error(), "inputs changed") {
		t.Fatalf("template failure not exercised: %v", err)
	}
	if _, err := os.Stat(target); !os.IsNotExist(err) {
		t.Fatalf("failed template published a partial project: %v", err)
	}
	stages, _ := filepath.Glob(filepath.Join(parent, ".roost-project-*"))
	if len(stages) != 0 {
		t.Fatalf("stage leaked: %v", stages)
	}
}
