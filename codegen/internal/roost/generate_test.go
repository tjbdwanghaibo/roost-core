// `roost generate` / `roost project sync` 先快照工程里的应用输入，提交前再核对，有变化就拒绝。工程运行期往工程目录写的
// 输出（`make dev-run` 的 `.dev/*.log`、DataEngine 默认 WAL 目录 `data/wal/dataengine`）不算应用输入、不进暂存树、
// 也不会被提交计划当成待删的生成物，dev-run 期间照常 generate / sync；真正的应用输入在生成期间被改仍然拒绝提交。
// 不能按目录名跳过 data（configs/data 是生成器的输出）。

// runtimeWrites stands in for a running dev-run: it appends to the dev log and
// to a WAL segment in the project, as the processes do while generation runs.
func runtimeWrites(t *testing.T, root string) {
	t.Helper()
	for _, rel := range []string{".dev/game.log", "data/wal/dataengine/000001.wal"} {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := f.WriteString("tick\n"); err != nil {
			t.Fatal(err)
		}
		if err := f.Close(); err != nil {
			t.Fatal(err)
		}
	}
}

func seedRuntimeOutput(t *testing.T, root string) {
	t.Helper()
	// A log line that quotes a generated header must not make the file look
	// like a codegen-owned output the commit plan may delete.
	writeProjectFile(t, root, ".dev/game.log", "starting\n")
	writeProjectFile(t, root, ".dev/quoted.log", "// Code generated by roost-codegen. DO NOT EDIT. (quoted in a log)\n")
	writeProjectFile(t, root, "data/wal/dataengine/000001.wal", "segment\n")
}

func assertRuntimeOutputKept(t *testing.T, root string) {
	t.Helper()
	for _, rel := range []string{".dev/game.log", ".dev/quoted.log", "data/wal/dataengine/000001.wal"} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel))); err != nil {
			t.Errorf("runtime output %s did not survive: %v", rel, err)
		}
	}
}

// fakeTidyGo puts a `go` on PATH whose `go mod tidy` runs script first, so
// GenerateTransactional's only external step doubles as the concurrent writer.
func fakeTidyGo(t *testing.T, script string) {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "bin")
	if err := os.Mkdir(bin, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(bin, "go"), []byte("#!/bin/sh\n"+script+"\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
}

func TestGenerateAndSyncIgnoreTheProjectsRuntimeOutput(t *testing.T) {
	if _, err := os.Stat("/bin/sh"); err != nil {
		t.Skip("the stand-in go is a POSIX shell script")
	}
	t.Run("generate while dev-run writes logs and WAL", func(t *testing.T) {
		root := copyOfNewProject(t, "configdata")
		seedRuntimeOutput(t, root)
		fakeTidyGo(t, "printf 'tick\\n' >> '"+filepath.Join(root, ".dev", "game.log")+"'; printf 'tick\\n' >> '"+filepath.Join(root, "data", "wal", "dataengine", "000001.wal")+"'")
		if err := GenerateTransactional(context.Background(), root, GenerateOptions{Stdout: io.Discard}, io.Discard); err != nil {
			t.Fatalf("generate while the project runs: %v", err)
		}
		assertRuntimeOutputKept(t, root)
	})
	t.Run("sync while dev-run writes logs and WAL", func(t *testing.T) {
		root := copyOfNewProject(t, "configdata")
		seedRuntimeOutput(t, root)
		syncProjectBeforeCommit = func() { runtimeWrites(t, root) }
		t.Cleanup(func() { syncProjectBeforeCommit = nil })
		if _, err := SyncProject(root); err != nil {
			t.Fatalf("sync while the project runs: %v", err)
		}
		assertRuntimeOutputKept(t, root)
	})
	t.Run("an application input edited during generate is still refused", func(t *testing.T) {
		root := copyOfNewProject(t, "configdata")
		rel := "configs/service/config.game.yaml"
		fakeTidyGo(t, "printf '# developer edit\\n' >> '"+filepath.Join(root, filepath.FromSlash(rel))+"'")
		err := GenerateTransactional(context.Background(), root, GenerateOptions{Stdout: io.Discard}, io.Discard)
		if err == nil || !strings.Contains(err.Error(), rel) {
			t.Fatalf("generate with %s edited concurrently = %v, want the inputs-changed refusal", rel, err)
		}
	})
}

// 生成器认定的运行期输出（`.dev`、`data/wal`，第二个进程的 data/wal/dataengine-<sid>）在生成的 .gitignore 里同样被忽略，
// `git add -A` 不会把 WAL 段提交进仓库；configs/data（生成器输出、要提交）不能被顺带忽略。

func TestGeneratedGitignoreIgnoresTheRuntimeOutputGenerationSkips(t *testing.T) {
	git, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git is not installed")
	}
	root := copyOfNewProject(t, "configdata")
	if out, err := exec.Command(git, "-C", root, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	ignored := func(rel string) bool {
		cmd := exec.Command(git, "-C", root, "check-ignore", "-q", "--no-index", filepath.FromSlash(rel))
		err := cmd.Run()
		if err == nil {
			return true
		}
		if exit, ok := err.(*exec.ExitError); ok && exit.ExitCode() == 1 {
			return false
		}
		t.Fatalf("git check-ignore %s: %v", rel, err)
		return false
	}
	for _, rel := range []string{
		".dev/game.log",
		"data/wal/dataengine/000001.wal",
		"data/wal/dataengine-2/000001.wal", // deploy/dev/second-game.sh 的独立 WAL 目录
	} {
		dir := strings.SplitN(rel, "/", 3)
		if !skippedProjectDirectory(filepath.ToSlash(filepath.Join(dir[0], dir[1]))) && !skippedProjectDirectory(dir[0]) {
			t.Fatalf("fixture drift: generation no longer skips %s, so this promise no longer applies", rel)
		}
		if !ignored(rel) {
			t.Errorf("generated .gitignore does not ignore %s, which generation itself treats as runtime output", rel)
		}
	}
	for _, rel := range []string{"configs/data/item.json", "data/README.md"} {
		if ignored(rel) {
			t.Errorf("generated .gitignore ignores %s; only the WAL directory is runtime output", rel)
		}
	}
}

// `generate --changed` 只跑改动涉及的生成器：git 给出的改动路径相对仓库根，要换算成相对工程根再与生成器前缀比较，
// 工程在仓库子目录（monorepo、examples/ 下的工程）时照样命中；porcelain 给带空格路径加的引号要去掉；改名两侧都算改动。

func gitIn(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestGenerateChangedSeesChangesOfAProjectInARepositorySubdirectory(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	repo := t.TempDir()
	project := filepath.Join(repo, "sub", "proj")
	writeFile(t, filepath.Join(project, "protocol", "def", "game.go"), "package def\n")
	writeFile(t, filepath.Join(repo, "other", "x.go"), "package other\n")
	gitIn(t, repo, "init", "-q")
	gitIn(t, repo, "add", ".")
	gitIn(t, repo, "commit", "-q", "-m", "base")

	writeFile(t, filepath.Join(project, "protocol", "def", "game.go"), "package def\n\n// changed\n")
	writeFile(t, filepath.Join(project, "db", "def", "hero cache.go"), "package def\n")
	writeFile(t, filepath.Join(repo, "other", "y.go"), "package other\n")

	changed, err := gitChanged(project)
	if err != nil {
		t.Fatal(err)
	}
	slices.Sort(changed)
	want := []string{"db/def/hero cache.go", "protocol/def/game.go"}
	if !slices.Equal(changed, want) {
		t.Fatalf("gitChanged = %q, want %q (paths relative to the project root, unquoted, nothing outside the project)", changed, want)
	}

	gens := []generator{
		{Name: "dao", Prefixes: []string{"db/def/"}},
		{Name: "protocol", Prefixes: []string{"protocol/def/"}},
		{Name: "tables", Prefixes: []string{"config/meta/"}},
		{Name: "registry", Always: true},
	}
	var names []string
	for _, gen := range filterChanged(gens, changed) {
		names = append(names, gen.Name)
	}
	if !slices.Equal(names, []string{"dao", "protocol", "registry"}) {
		t.Fatalf("filterChanged selected %q, want dao, protocol and registry", names)
	}
}

