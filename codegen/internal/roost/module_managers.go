// 模块的后台 manager（维护者 D22，2026-11-14）：不在模块 runtime: 里的后台循环做成 manager，代码写在 game/managers，
// 在 game/managers/managers.go 的 Managers() 里登记，由 manager Mod 统一启停（依赖先启、反序停、停机带期限）。
//
// 清单写 managers: [<构造函数名>]：函数在模块的 files/game/managers/ 下的模板里定义（package managers，
// 签名 func() app.IManager）。安装器把 "<构造函数名>()," 加到 Managers() 返回的列表末尾；已经有了就不加。
// managers.go 是业务文件：安装器只往那个列表里加一行，别的不碰；列表找不到（业务把 Managers 改成了别的写法）时
// 拒绝安装并说明要加哪一行。只对 manager 登记点在 game/managers/managers.go 的工程生效（v1.47.0 起新生成的工程）。

// moduleManagersDir 是模块 manager 模板的落点目录（package managers）。
const moduleManagersDir = "game/managers/"

// validateModuleManagers 检查清单的 managers：构造函数名是导出的标识符、不重复；模块带了 game/managers 下的模板；
// needs.mods 写了 manager（没有 manager Mod 就没有人启停它们）；入口落在托管框架服务上的模块不能带（manager 在 game 服务里启动）。
func validateModuleManagers(spec ModuleSpec) error {
	if len(spec.Managers) == 0 {
		return nil
	}
	seen := map[string]bool{}
	for _, name := range spec.Managers {
		if !modulePascalPattern.MatchString(name) || seen[name] {
			return fmt.Errorf("managers: %q must be a unique exported constructor name (func() app.IManager in package managers)", name)
		}
		seen[name] = true
	}
	hasFile := false
	for _, rel := range spec.Files {
		if strings.HasPrefix(rel, moduleManagersDir) && path.Dir(rel) == strings.TrimSuffix(moduleManagersDir, "/") &&
			strings.HasSuffix(rel, ".go") && !strings.HasSuffix(rel, "_test.go") {
			hasFile = true
		}
	}
	if !hasFile {
		return fmt.Errorf("managers: files/%s has no .go template defining %s", moduleManagersDir, strings.Join(spec.Managers, ", "))
	}
	if !contains(spec.Needs.Mods, "manager") {
		return fmt.Errorf("managers: needs.mods must list manager (the manager Mod starts and stops them)")
	}
	if spec.Runtime != nil && spec.Runtime.Framework != "" {
		return fmt.Errorf("managers: a module whose runtime runs in a hosted framework service cannot register game managers")
	}
	return nil
}

// moduleManagersEdit 返回把 spec 的 manager 登记进 game/managers/managers.go 之后的内容（plan 与 add 共用，plan 不写盘）。
// changed 为 false 表示都已经登记过。service 是模块装进的业务服务：它的 manager 登记点必须是 game/managers/managers.go。
func moduleManagersEdit(root string, manifest Manifest, service string, spec ModuleSpec) (body []byte, changed bool, err error) {
	if !moduleManagersHost(root, manifest, service) {
		return nil, false, fmt.Errorf("module %s registers managers (%s) in %s, but service %s does not keep its manager list there "+
			"(only projects generated by v1.47.0 or later with the manager mod on the game service do; register them in your own manager list by hand)",
			spec.Name, strings.Join(spec.Managers, ", "), gameManagersPath, service)
	}
	file := filepath.Join(root, filepath.FromSlash(gameManagersPath))
	raw, err := os.ReadFile(file)
	if err != nil {
		return nil, false, fmt.Errorf("module %s: %w", spec.Name, err)
	}
	body, changed, err = appendManagerRegistrations(raw, spec.Managers)
	if err != nil {
		return nil, false, fmt.Errorf("module %s: %s: %w; add %s to the list Managers() returns yourself, then install again",
			spec.Name, gameManagersPath, err, managerCalls(spec.Managers))
	}
	return body, changed, nil
}

// moduleManagersHost 报告 service 的 manager 列表是不是 game/managers/managers.go。规则同 gameManagersService
// （装了 manager Mod、服务目录里没有 v1.47.0 之前的 managers.go），但 game/ 目录树的归属只在说得清时才比对：
// 还没有玩家接入、同一次安装又加了别的 Nest 服务（alliance）时 gameManagersService 判断不了，返回空串——
// 模块装进的服务就是 roost module add 选定的那一个（缺省是玩家接入所在的服务），这时按它算。
func moduleManagersHost(root string, manifest Manifest, service string) bool {
	if _, ok := manifest.Services[service]; !ok || manifest.isFrameworkService(service) {
		return false
	}
	if mods, err := resolveMods(effectiveServiceMods(manifest, service)); err != nil || !contains(mods, "manager") {
		return false
	}
	if _, err := os.Stat(filepath.Join(root, "internal", "service", service, "managers.go")); err == nil {
		return false
	}
	owner := gameManagersService(root, manifest)
	return owner == "" || owner == service
}

// writeModuleManagers 把 spec 的 manager 登记进 game/managers/managers.go。在 AddModules 的回滚边界内调用（文件已备份）。
func writeModuleManagers(root string, manifest Manifest, service string, spec ModuleSpec) error {
	if len(spec.Managers) == 0 {
		return nil
	}
	body, changed, err := moduleManagersEdit(root, manifest, service, spec)
	if err != nil || !changed {
		return err
	}
	return writeAtomic(filepath.Join(root, filepath.FromSlash(gameManagersPath)), body, 0o644)
}

func managerCalls(names []string) string {
	calls := make([]string, len(names))
	for i, name := range names {
		calls[i] = name + "()"
	}
	return strings.Join(calls, ", ")
}

// appendManagerRegistrations 在 Managers() 返回的列表字面量末尾加上 "<name>()," （已有同名调用的跳过），保留其余文本与注释。
// 认得的写法只有生成的那一种：func Managers() []app.IManager { return []app.IManager{ ... } }。
func appendManagerRegistrations(src []byte, names []string) ([]byte, bool, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, gameManagersPath, src, parser.ParseComments)
	if err != nil {
		return nil, false, err
	}
	var list *ast.CompositeLit
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "Managers" || fn.Body == nil {
			continue
		}
		for _, stmt := range fn.Body.List {
			ret, ok := stmt.(*ast.ReturnStmt)
			if !ok || len(ret.Results) != 1 {
				continue
			}
			if lit, ok := ret.Results[0].(*ast.CompositeLit); ok {
				if _, slice := lit.Type.(*ast.ArrayType); slice {
					list = lit
				}
			}
		}
	}
	if list == nil {
		return nil, false, fmt.Errorf("func Managers does not return a []app.IManager{...} literal")
	}
	present := map[string]bool{}
	for _, element := range list.Elts {
		if call, ok := element.(*ast.CallExpr); ok {
			if ident, ok := call.Fun.(*ast.Ident); ok && len(call.Args) == 0 {
				present[ident.Name] = true
			}
		}
	}
	var lines strings.Builder
	for _, name := range names {
		if !present[name] {
			fmt.Fprintf(&lines, "\t\t%s(),\n", name)
			present[name] = true
		}
	}
	if lines.Len() == 0 {
		return src, false, nil
	}
	at := fset.Position(list.Rbrace).Offset
	// 右花括号单独一行时插在那一行之前；与内容同一行（例如空列表 {}）时先换行。
	lineStart := bytes.LastIndexByte(src[:at], '\n') + 1
	insert := lines.String()
	if before := strings.TrimSpace(string(src[lineStart:at])); before == "" {
		at = lineStart
	} else {
		insert = "\n" + insert
		if len(list.Elts) > 0 && !strings.HasSuffix(before, ",") {
			// 一行写完的列表（{scene.Mgr}）最后一个元素后面没有逗号。
			insert = "," + insert
		}
	}
	edited := make([]byte, 0, len(src)+len(insert))
	edited = append(edited, src[:at]...)
	edited = append(edited, insert...)
	edited = append(edited, src[at:]...)
	formatted, err := format.Source(edited)
	if err != nil {
		return nil, false, err
	}
	return formatted, true, nil
}
