func renderProductionDeployment(m Manifest) map[string]string {
	files := map[string]string{
		"deploy/shell/build.sh":                             renderShellBuild(m),
		"deploy/shell/install.sh":                           renderShellInstall(m),
		"deploy/shell/rollback.sh":                          renderShellRollback(m),
		"deploy/shell/healthcheck.sh":                       renderShellHealthcheck(),
		"deploy/shell/README.md":                            renderShellReadme(m),
		"deploy/docker/README.md":                           renderDockerReadme(m),
		"deploy/docker/docker-compose.prod.yaml":            renderProductionCompose(m),
		"deploy/docker/env.example":                         renderDockerEnvExample(),
		"deploy/docker/deploy.sh":                           renderDockerDeployScript(m),
		"deploy/docker/rollback.sh":                         renderDockerRollbackScript(m),
		"deploy/k8s/base/namespace.yaml":                    renderKubernetesNamespace(),
		"deploy/k8s/base/service-account.yaml":              renderKubernetesServiceAccount(m),
		"deploy/k8s/base/network-policy.yaml":               renderKubernetesNetworkPolicy(m),
		"deploy/k8s/README.md":                              renderKubernetesReadme(m),
		"deploy/k8s/deploy.sh":                              renderKubernetesDeployScript(m),
		"deploy/k8s/overlays/staging/kustomization.yaml":    renderKubernetesOverlay("staging"),
		"deploy/k8s/overlays/production/kustomization.yaml": renderKubernetesOverlay("production"),
	}

	services := sortedServiceNames(m)
	resources := []string{"namespace.yaml", "service-account.yaml", "network-policy.yaml"}
	for _, service := range services {
		files["deploy/k8s/base/"+service+".yaml"] = renderKubernetesWorkload(m, service)
		files["deploy/k8s/base/"+service+"-pdb.yaml"] = renderKubernetesPDB(m, service)
		files["deploy/k8s/base/secret."+service+".example.yaml"] = renderKubernetesSecretExample(m, service)
		resources = append(resources, service+".yaml", service+"-pdb.yaml")
	}
	// The base lives in its own directory. kustomize (v5.7+, shipped with
	// kubectl 1.34+) refuses a base that is an ANCESTOR of the overlay
	// referencing it — "cycle detected: candidate root deploy/k8s contains
	// visited root deploy/k8s/overlays/staging" — which is what
	// deploy/k8s/kustomization.yaml + overlays/*/../.. was.
	files["deploy/k8s/base/kustomization.yaml"] = renderKubernetesKustomization(resources)
	// Every owned manifest under base/ carries the generated header. sync
	// only removes an obsolete output it can recognise as codegen's, and the
	// 2026-09 move of the base into base/ showed what happens without it:
	// the old files stayed behind, unowned and unremovable.
	for path, body := range files {
		if strings.HasPrefix(path, "deploy/k8s/base/") && !strings.HasPrefix(path, "deploy/k8s/base/secret.") &&
			!strings.HasPrefix(body, "# Code generated") {
			files[path] = "# Code generated by roost-codegen. DO NOT EDIT.\n" + body
		}
	}
	return files
}

