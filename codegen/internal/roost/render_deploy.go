// startupAllowance is how long a service may take from process start to
// ready, as the deployment templates wait for it. A service whose generated
// config turns the singleton on (serviceSingletonEnabled) may first wait up to
// singleton.startup_wait for the key a previous process still holds — it
// crashed, or its stop ran out of time — and only then replays the WAL
// (dataengine.startup_timeout); a normal rolling deploy stops the old process
// first and does not wait. Other services keep the 30s the templates always had.
func startupAllowance(m Manifest, service string) time.Duration {
	allowance := 30 * time.Second
	if serviceSingletonEnabled(m, service) {
		allowance = max(allowance, generatedSingletonStartupWait+generatedDataEngineStartupTimeout)
	}
	return allowance
}

// renderShellHealthAttempts is the per-service default readiness wait of
// install.sh and rollback.sh: one attempt a second for startupAllowance.
// SERVICE is checked against the same list before this runs.
func renderShellHealthAttempts(m Manifest) string {
	var b strings.Builder
	b.WriteString("# Readiness attempts, one a second. A service with singleton.enabled may first wait up to\n")
	b.WriteString("# singleton.startup_wait for the lock a previous process still holds, then replay its WAL\n")
	b.WriteString("# (dataengine.startup_timeout); raise HEALTH_ATTEMPTS when raising either.\n")
	b.WriteString("case \"$SERVICE\" in\n")
	for _, service := range sortedServiceNames(m) {
		fmt.Fprintf(&b, "  %s) DEFAULT_HEALTH_ATTEMPTS=%d ;;\n", service, int64(startupAllowance(m, service)/time.Second))
	}
	b.WriteString("  *) DEFAULT_HEALTH_ATTEMPTS=30 ;;\nesac\n")
	b.WriteString("HEALTH_ATTEMPTS=${HEALTH_ATTEMPTS:-$DEFAULT_HEALTH_ATTEMPTS}\n")
	return b.String()
}

// renderStatefulWALGuard is the install-time check that a stateful service's
// production config keeps its WAL under the instance's state root. It is a
// `case` on the service NAME with the stateful services as alternatives —
// not a `case` on a constant word list matched against a "*$SERVICE*"
// pattern, which shellcheck rejects (SC2194) and which would also match a
// service whose name is a substring of another's. With no stateful service
// the block is omitted rather than rendered as an empty (invalid) case.
func renderStatefulWALGuard(stateful []string) string {
	if len(stateful) == 0 {
		return ""
	}
	return `case "$SERVICE" in
  ` + strings.Join(stateful, "|") + `)
    if ! grep -F "$STATE_ROOT/wal" "$CONFIG_SOURCE" >/dev/null 2>&1; then
      printf 'nest.wal.dir in %s must be %s/wal for service %s\n' "$CONFIG_SOURCE" "$STATE_ROOT" "$SERVICE" >&2
      exit 2
    fi
    ;;
esac

`
}

// renderStatsLogLink points the relative stats_log.dir under the unit's
// WorkingDirectory — the release, see renderShellConfigData — at LOG_ROOT
// (RR-20260928-04). The release is read-only to the service (root-owned, and
// ProtectSystem=strict), so the stats file was never written there; LOG_ROOT is
// the instance's log directory, owned by the run user and already in
// ReadWritePaths. Each release carries its own link, so a rollback keeps
// writing to the same place. Omitted when no service enables stats_log.
func renderStatsLogLink(m Manifest) string {
	for _, service := range sortedServiceNames(m) {
		if serviceUsesStatsLog(m, service) {
			return `# stats_log.dir is relative (` + defaultStatsLogDir + `) and resolves under WorkingDirectory.
ln -sfn "$LOG_ROOT" "$RELEASE_ROOT/` + defaultStatsLogDir + `"
`
		}
	}
	return ""
}

// renderShellConfigData installs the configdata tables into the release for
// the services that load them (RR-20260928-05).
//
// config_data.dir is relative (configs/data) and resolves against the unit's
// WorkingDirectory. That used to be $APP_ROOT, and nothing installed the data
// there, so a configdata service installed by this script stopped at start with
// "configdata: stat dir configs/data: no such file or directory". The layout now
// matches the image (RR-20260927-34, WORKDIR /app holding the binary and
// configs/data): the tables go into the release next to the binary they were
// generated for, and WorkingDirectory is $APP_ROOT/current, which systemd
// resolves when the process starts — a switch of current (install, rollback.sh)
// takes effect with the restart that follows it, and a running process keeps
// reading (and Reloading) its own release's tables until then.
//
// guard runs before the release directory exists, so a missing data directory
// does not leave behind an "immutable" release that blocks the next attempt.
func renderShellConfigData(m Manifest) (guard, install string) {
	var services []string
	for _, service := range sortedServiceNames(m) {
		if serviceUsesConfigData(m, service) {
			services = append(services, service)
		}
	}
	if len(services) == 0 {
		return "", ""
	}
	arm := strings.Join(services, "|")
	guard = `CONFIG_DATA=${CONFIG_DATA:-"$ROOT/` + defaultConfigDataDir + `"}
case "$SERVICE" in
  ` + arm + `)
    [ -f "$CONFIG_DATA/_manifest.json" ] || { printf 'config data not found: %s/_manifest.json; run make generate or set CONFIG_DATA\n' "$CONFIG_DATA" >&2; exit 2; }
    ;;
esac
`
	install = `# config_data.dir is relative (` + defaultConfigDataDir + `) and resolves under WorkingDirectory, the release.
case "$SERVICE" in
  ` + arm + `)
    install -d -m 0755 "$RELEASE_ROOT/configs"
    cp -R "$CONFIG_DATA" "$RELEASE_ROOT/` + defaultConfigDataDir + `"
    chmod -R u+rwX,go+rX,go-w "$RELEASE_ROOT/` + defaultConfigDataDir + `"
    ;;
esac
`
	return guard, install
}

