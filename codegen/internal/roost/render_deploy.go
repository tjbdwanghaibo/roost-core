func indentText(value, prefix string) string {
	lines := strings.Split(strings.TrimSuffix(value, "\n"), "\n")
	for i := range lines {
		lines[i] = prefix + lines[i]
	}
	return strings.Join(lines, "\n") + "\n"
}
