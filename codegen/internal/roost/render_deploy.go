// renderShellUnitRecord 是 install.sh 与 rollback.sh 共用的两个函数：每个 release
// 在它自己安装时写的 systemd unit 下运行（RR-20260928-10）。
//
// unit 由构建该 release 的那一版生成器的 install.sh 写出，形态随生成器变化——
// RR-20260928-05 把 WorkingDirectory 从 $APP_ROOT 改成了 $APP_ROOT/current（configdata
// 在那里找数据表）。之前两个脚本回退时只切 current：升级失败后 install.sh 在新 unit 下
// 重启上一个 release，RR-05 之前安装的 release 里没有 configs/data，照样 "stat dir
// configs/data" 起不来，报 "rollback also failed readiness"，即使运维为旧 unit 在
// $APP_ROOT/configs/data 放好了数据；rollback.sh 的手工回退同样如此（临时根演练实测）。
//
// 所以 unit 按 release 记在 $APP_ROOT/units/<version>.service，与 current 一起切换。
// record_unit 在任何覆盖之前把当前 release 正在用的 unit 记给它——这是旧 install.sh
// 装的 release 唯一能得到记录的时机；没有记录的 release 沿用已安装的 unit（修前行为）。
//
// 两个脚本都按 stop（当前装载的 unit）→ 切 current → use_unit → start 的顺序切换
// （RR-20260928-12）。之前是 use_unit 之后 systemctl restart：daemon-reload 后 restart 里的
// stop 用的是刚装载的目标 unit 的 TimeoutStopSec，正在运行的进程按别的 release 的停机预算
// 被停（rollback.sh 回 v1 时 v2 进程按 v1 较短的预算，超时即 SIGKILL）。stop 失败时 set -e
// 在改动任何东西之前退出，不能吞掉：服务还在运行时 start 是空操作，旧进程会被当成新版本
// 通过 readiness。use_unit 失败（install / daemon-reload）时切回上一个 release 及其 unit
// 再启动并报错退出，不再像之前那样在 set -e 下留下 current 已切换、unit 与进程都没换。
func renderShellUnitRecord() string {
	return `# Each release runs under the systemd unit it was installed with, recorded in
# $APP_ROOT/units/<version>.service and switched together with current.
record_unit() {
  install -d -m 0755 "$APP_ROOT/units"
  [ -n "$1" ] && [ -f "$UNIT_PATH" ] || return 0
  [ -e "$APP_ROOT/units/${1##*/}.service" ] || install -m 0644 "$UNIT_PATH" "$APP_ROOT/units/${1##*/}.service"
}
use_unit() {
  if [ ! -f "$APP_ROOT/units/${1##*/}.service" ]; then
    printf 'no unit recorded for release %s; keeping %s\n' "${1##*/}" "$UNIT_PATH" >&2
    return 0
  fi
  install -m 0644 "$APP_ROOT/units/${1##*/}.service" "$UNIT_PATH"
  systemctl daemon-reload
}
`
}

func renderShellReadme(m Manifest) string {
	value := replaceDeployTokens(`# Shell/systemd 部署

1. sh deploy/shell/build.sh 构建 Linux 静态二进制。
2. 从 configs/service/config.<service>.prod.example.yaml 复制生产配置，替换全部 CHANGE_ME，为每个 SID 设置独占 WAL 目录。
3. 执行 sudo sh deploy/shell/install.sh <service> <sid> <version> <config>。
4. 用 sh deploy/shell/healthcheck.sh 验证 readiness。
5. 需要人工回退时执行 sudo sh deploy/shell/rollback.sh <service> <sid> <installed-version>。

安装器把二进制和配置写入不可变版本化 releases 目录并生成 SHA256SUMS，原子切换 current；unit 的 WorkingDirectory 是 current 指向的 release，相对的 config_data.dir（configs/data）与 stats_log.dir（log）都按它解析——用 configdata 的 Service 安装时把工程里的 configs/data（可用 CONFIG_DATA 指定）拷进 release，与镜像布局一致，每个 release 里的 log 链接到实例日志目录 /var/log/roost/<instance>（LOG_ROOT，服务唯一可写的日志位置）；创建专用 systemd unit、非登录用户、只读系统保护和按 Service 生成的 SIGTERM 停机预算：TimeoutStopSec = max(该 Service 按实际注册的 Mod 生成的 shutdown.total_timeout, 配置里实际的 total_timeout) + 5s，当前为 {{STOP_BUDGETS}}；增减 Mod 或调大 total_timeout 后执行 roost project sync 重算。同一版本名拒绝覆盖。每个 release 在它自己安装时写的 systemd unit 下运行：unit 记在 $APP_ROOT/units/<version>.service，覆盖前先把正在用的那份记给当前 release，切换 current 时一并装回目标 release 的 unit 并 daemon-reload；切换前先按正在用的 unit 停掉当前进程，正在运行的版本按它自己 unit 的 TimeoutStopSec 停机，再装入目标 unit 启动。readiness 未在预算内成功、或目标 unit 装不上（install / daemon-reload 失败）时自动切回上一 release 及其 unit；首次安装失败则停服。rollback.sh 只允许切换到已经安装且不可变的版本（版本号不能是 . 或 ..），目标版本 readiness 失败或 unit 装不上会恢复原版本并以非零退出。多实例部署必须使用不同 SID、配置文件和 WAL 目录；不要让两个进程共享 WAL。可用 HEALTH_URL/HEALTH_ATTEMPTS 覆盖探测地址和次数；HEALTH_ATTEMPTS 默认按 Service（每秒一次），打开 singleton（App 单实例锁）的 Service 先可能等旧进程的锁最多 singleton.startup_wait、再做 WAL 重放（dataengine.startup_timeout），当前为 {{HEALTH_DEFAULTS}}，调大这两个值时同步调大。

统计文件 LOG_ROOT/<service>-<sid>.stats.log 不轮转：statslog 以 O_APPEND 打开它、进程运行期间不重开，长期运行的实例由运维配 logrotate，必须用 copytruncate（create / 改名式轮转会让进程继续写旧文件，新文件一直是空的；也没有可发的 reload 信号）。示例 /etc/logrotate.d/{{APP}}-stats：

    /var/log/roost/*/*.stats.log {
        daily
        rotate 14
        compress
        delaycompress
        missingok
        notifempty
        copytruncate
    }

copytruncate 在复制与截断之间追加的记录会丢，至多一条（默认 stats_log.interval 1 分钟）；同一份数据每次采集都已发布为 metrics gauge 与 ops /statsz，统计文件只是旁路留档。
`, m)
	// audit8 D3：停机预算按 Service 的 Mod 生成（RR-20260926-66），与 install.sh 的
	// STOP_TIMEOUT 同一来源；这里原来写死“45 秒”，是 RR-66 之前的固定值。
	var budgets []string
	for _, service := range sortedServiceNames(m) {
		budgets = append(budgets, service+" "+seconds(serviceShutdownPlan(m, service).grace))
	}
	value = strings.ReplaceAll(value, "{{STOP_BUDGETS}}", strings.Join(budgets, "、"))
	var attempts []string
	for _, service := range sortedServiceNames(m) {
		attempts = append(attempts, fmt.Sprintf("%s %d", service, int64(startupAllowance(m, service)/time.Second)))
	}
	return strings.ReplaceAll(value, "{{HEALTH_DEFAULTS}}", strings.Join(attempts, "、"))
}

