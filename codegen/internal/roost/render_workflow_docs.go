import "strings"

func renderBeginnerWorkbook(manifest Manifest) string {
	const guide = `<!-- Code generated by roost-codegen. DO NOT EDIT. -->
# {{NAME}} 小白逐步操作手册

这份手册不要求先理解 Roost。原则只有两个：一次只做一个动作；每完成一个动作就运行 project next。
工具不会用 preset 替你决定字段、玩法或鉴权，但会检查当前项目并告诉你唯一的下一步。

## 0. 先记住三个命令

    roost project next
    roost project doctor --workflow first-business
    make test

- next：不报一整墙错误，只告诉当前一步、原因和对应文档；未完成也返回成功。
- doctor：阶段验收，缺少任何必要边界都会失败，适合提交前和 CI。
- test：编译并运行项目测试。generated 文件也会参与编译。

## 1. 文件能不能改

先看文件第一行：带 Code generated by roost-codegen 和 DO NOT EDIT 的文件不修改。修改声明源后重新
运行 roost generate 或 make sync。没有生成标识的 Entity、Component、DAO 定义、handler、endpoint、
auth.go 和 Service 文件归业务所有。

| 想改什么 | 修改位置 | 然后运行 |
| --- | --- | --- |
| 协议字段 | protocol/def/*.go | roost generate |
| 持久化/同步字段 | db/def/*.go | roost generate |
| 玩法方法 | game/entities/*/*_component.go | make test |
| Nest 业务命令 | game/handler/*.go | roost generate |
| 协议到 Sender 映射 | game/controllers/*/*.go | make test |
| 登录票据校验 | internal/access/player/tcp/auth.go | roost config enable player-tcp |
| Service 生命周期 | internal/service/{{SERVICE}}/service.go | make test |

## 2. 第一次进入项目

在项目根目录执行：

    make deps-update
    roost project next

如果 deps-update 失败，先修复 GOPROXY、DNS 或 GitHub 访问；不要把个人电脑绝对路径 replace 提交到
go.mod。next 的典型输出是 workflow、progress、next、why、check again 和 guide。只执行 next 那一行，
不要一次复制后面所有阶段。

## 3. 第一条业务：修改玩家名字

下面列出完整路线，实际操作仍以 project next 当前输出为准。

### 3.1 接入边界和聚合

    roost add access player --service {{SERVICE}}
    roost project next
    roost add entity Player
    roost project next
    roost add component Profile --entity Player
    roost project next
    roost add dao Player --entity Player

access 只负责已认证请求进入协议层；Entity 是锁和生命周期边界；Component 放玩法；DAO 放需要保存或
同步的状态。不要在 Service/controller 里直接保存裸 Entity 指针。

### 3.2 声明状态

编辑 db/def/player.go，在 PlayerDao 中加入：

    Name string ` + "`bson:\"name\" dao:\"persist,sync\"`" + `

然后运行：

    roost generate

业务以后读取 dao.GetName()，修改 dao.SetName(value)。不能直接读写私有字段，也不能绕过 mutator；
mutator 同时维护 dirty、undo、持久化 patch 和客户端同步标记。

### 3.3 写玩法方法

编辑 game/entities/player/profile_component.go，加入：

    func (component *ProfileComponent) Rename(name string) error {
        name = strings.TrimSpace(name)
        if name == "" { return errors.New("name is required") }
        if len(name) > 24 { return errors.New("name is too long") }
        component.Owner().Dao().SetName(name)
        return nil
    }

同时加入 errors 和 strings import。Component 已在 Nest 持有 Entity mutex 后执行，业务层不要再加锁。

### 3.4 生成并修改 Nest handler

    roost add handler RenamePlayer --entity Player --component Profile

把 game/handler/rename_player.go 改为：

    //roost:nest rollback=undo durability=strict
    func handlerRenamePlayer(target player.IProfileEntity, name string) error {
        return target.ProfileComp().Rename(name)
    }

第一个参数是锁目标；其余参数名必须能与协议 Request 字段对应。关键写使用 strict；普通可恢复玩法可在
理解 WAL 语义后选择 async。不要为了快把交易改成 memory。

### 3.5 协议和 endpoint

    roost add protocol RenamePlayer --group game --handler player

编辑 protocol/def/rename_player.go：

    type RenamePlayerRequest struct {
        Name string ` + "`pb:\"1\"`" + `
    }

然后执行：

    roost add endpoint RenamePlayer --handler player
    roost add lifecycle Player --service {{SERVICE}}
    roost generate
    roost project doctor --workflow first-business
    make test

endpoint 自动用已认证的 PlayerID 调生成 Sender。不要在 endpoint 直接拿 EntityManager、手动加锁或直接
调用 Component。lifecycle 只用于登录加载、首次创建和销毁，普通玩法都走 Sender。

## 4. 接真实 TCP 客户端（可选）

如果已有独立网关，可以实现同一个 gateway.Session/Dispatch 边界并跳过本节。使用框架自带 TCP：

    roost add transport tcp
    roost project next --workflow player-tcp

命令已经把完整 TCP 配置以 enabled: false 加入 {{SERVICE}} 配置和生产示例，不需要复制 YAML。
它生成 listener、限帧、连接上限、超时、背压、sequence、关停、指标和主动推送。

### 4.1 完成鉴权

编辑 internal/access/player/tcp/auth.go：

- 在 newApplicationAuthenticator 中从 Viper/Secret 引用构造不可变 verifier；初始化失败就返回错误；
- Authenticate 只验证服务端签名、过期时间、登录代次、设备绑定和重放信息；
- 成功必须返回非零 PlayerID 和非空 SessionID；
- 永远不信任客户端自报 PlayerID，不把长期密钥写进仓库。

生成骨架默认返回 ErrUnauthenticated。不要为了让 doctor 变绿而写固定 PlayerID 或 accept-all；这会把
所有客户端认证成同一玩家。鉴权实现完成后：

    roost config enable player-tcp
    roost project doctor --workflow player-tcp
    make test-race

enable 会检查默认骨架并只改 enabled；停流使用 roost config disable player-tcp。

### 4.2 主动推送

从 Registry 获取 playertcp.Runtime，PushPlayer 发给玩家全部 Session，PushSession 发给一个 Session。
离线返回 ErrSessionNotFound。在线推送不是持久化：奖励、交易、邮件先写权威状态或 outbox，再推送提示。

## 5. 启动与验证

轻量 configdata 项目：

    make run SERVICE={{SERVICE}}

启用了 Mongo、Redis、NATS、etcd 时：

    make dev-up
    make run SERVICE={{SERVICE}}

另开终端检查 ops readyz。实际路径和端口以 configs/service/config.{{SERVICE}}.yaml 为准。启动成功不等于
可发布：必须真实测试创角、冷加载、同玩家并发请求、错误 token、断线重连、慢客户端和 SIGTERM。

## 6. 每次新增功能的固定套路

1. 用 roost add 创建声明骨架；
2. 只编辑业务所有文件；
3. roost generate；
4. roost project next；
5. make test；
6. 提交前 make ci。

新增字段先判断：只临时计算就放 Component；需要保存或同步就放 DAO；客户端输入放 Protocol Request；
跨 Entity/跨服务写进入 Nest/Saga，不在 controller 拼分布式锁。

## 7. 报错时按这个顺序

    roost project next
    roost project doctor --workflow first-business
    roost generate --check
    go test ./...
    go test -race ./...

不要手改 generated 文件消除编译错误。next 不理解时看它输出的 guide；常见错误对照
docs/TROUBLESHOOTING.zh-CN.md。仍无法定位时保留完整命令、错误输出、roost.yaml 和相关声明文件。

## 8. 发布前逐项勾选

- project doctor 两个工作流通过（未使用内置 TCP 时记录替代网关验收）；
- make ci、生成物 freshness、race、vet 通过；
- 生产配置没有 CHANGE_ME/localhost/dev 默认值，Secret 不进 Git；
- 数据库/NATS/Redis 使用生产拓扑，WAL/PVC、备份、恢复演练完成；
- listener 有 TLS 边界、连接/限流、FD、LB idle 和监控告警；
- 灰度、readiness、SIGTERM、回滚和版本兼容已演练。

更深入阅读顺序：FIRST_BUSINESS → ENTITY_COMPONENT → PROTOCOL_TO_NEST → PLAYER_ACCESS_TCP →
IMPLEMENTATION → DEPLOYMENT。
`
	return strings.NewReplacer("{{NAME}}", manifest.Project.Name, "{{SERVICE}}", sortedServiceNames(manifest)[0]).Replace(guide)
}

