func TestRunRetiresEntityWireAfterLastMarkerRemoved(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "player.go")
	write := func(marker string) {
		t.Helper()
		if err := os.WriteFile(source, []byte("package game\nconst EntityKindPlayer = 1\n//"+marker+"\ntype Player struct{}\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	wire := filepath.Join(dir, "player_gen_wire.go")
	if _, err := os.Stat(wire); err != nil {
		t.Fatalf("generated wire missing: %v", err)
	}
	guard := guardTestFileFor(wire)
	if err := os.WriteFile(guard, []byte("// Code generated by tool/entity. DO NOT EDIT.\npackage game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	manual := filepath.Join(dir, "manual_gen_wire.go")
	if err := os.WriteFile(manual, []byte("package game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{wire, guard} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Errorf("retired output remains %s: %v", path, err)
		}
	}
	if _, err := os.Stat(manual); err != nil {
		t.Fatalf("manual file removed: %v", err)
	}
}

func TestRunMovesRegistrationWhenFirstSiblingIsRetired(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "entities.go")
	write := func(alphaMarker string) {
		t.Helper()
		body := "package game\nconst (EntityKindAlpha = 1; EntityKindBeta = 2)\n//" + alphaMarker + "\ntype Alpha struct{}\n//roost:entity entityKind=EntityKindBeta\ntype Beta struct{}\n"
		if err := os.WriteFile(source, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "alpha_gen_wire.go")); !os.IsNotExist(err) {
		t.Fatalf("retired sibling wire remains: %v", err)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "beta_gen_wire.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(raw), "func RegisterEntity()") || !strings.Contains(string(raw), "//roost:register phase=entity") {
		t.Fatal("remaining sibling did not take over the package registration")
	}
}

// v1.47.0：每个实体包生成 lifecycle_gen.go（core 泛型 entitylifecycle 的具名入口）。只有一个实体时用短名
// （player.LifecycleFromRegistry），几个实体共用一个包时带实体名，避免同名冲突；只剩只读 DTO 的包删掉它。
func TestRunGeneratesEntityLifecycle(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("player.go", "package player\nconst EntityKindPlayer = 1\n//roost:entity entityKind=EntityKindPlayer\ntype Player struct{}\n")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	lifecycle := filepath.Join(dir, "lifecycle_gen.go")
	raw, err := os.ReadFile(lifecycle)
	if err != nil {
		t.Fatalf("lifecycle not generated: %v", err)
	}
	for _, want := range []string{
		"// Code generated by tool/entity. DO NOT EDIT.", "package player",
		"type Lifecycle = entitylifecycle.Lifecycle[*Player]",
		"func LifecycleFromRegistry(registry *app.Registry) (*Lifecycle, error)",
		`entitylifecycle.FromRegistry[*Player](registry, EntityKindPlayer, "player", ErrNotFound)`,
		`var ErrNotFound = errors.New("player lifecycle: Entity not found")`,
	} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("lifecycle lacks %q:\n%s", want, raw)
		}
	}
	write("player.go", "package player\nconst (EntityKindPlayer = 1; EntityKindPlayerShadow = 2)\n//roost:entity entityKind=EntityKindPlayer\ntype Player struct{}\n//roost:entity entityKind=EntityKindPlayerShadow\ntype PlayerShadow struct{}\n")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	raw, _ = os.ReadFile(lifecycle)
	for _, want := range []string{"func PlayerLifecycleFromRegistry(", "func PlayerShadowLifecycleFromRegistry(", "var ErrPlayerShadowNotFound"} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("two-entity lifecycle lacks %q:\n%s", want, raw)
		}
	}
	if strings.Contains(string(raw), "func LifecycleFromRegistry(") {
		t.Errorf("two entities must not share the short name:\n%s", raw)
	}
}

// v1.47.0：实体包在 <模块>/game/entities/ 下时，生成器为它写 game/view/entity_<snake>.go（实体接口嵌入挂载组件的
// <X>Holder 与 DAO getter），并在 wire 里给出返回 view 接口的访问器；没有 Holder 的组件、冷组件不带。
// 实体去掉后，它的 view 文件随下一次全量生成删除。
func TestRunGeneratesViewEntityAndAccessors(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/g\n\ngo 1.24\n")
	write("game/view/component_bag.go", "package view\n\ntype Bag interface{ Count(itemID int64) int64 }\n\ntype BagHolder interface{ Bag() Bag }\n")
	write("game/entities/player/player.go", `package player

import (
	db "example.com/g/db"
	"github.com/tjbdwanghaibo/roost-core/framework/entity"
)

const EntityKindPlayer = 1

const (
	CompTypeBag   entity.ComponentType = 1
	CompTypeQuest entity.ComponentType = 2
)

type BagComponent struct{ entity.ComponentBase }
type QuestComponent struct{ entity.ComponentBase }

//roost:entity entityKind=EntityKindPlayer
type Player struct {
	*entity.EntityBase
	dao   *db.PlayerDao   `+"`dao:\"player\"`"+`
	bag   *BagComponent   `+"`comp:\"CompTypeBag\"`"+`
	quest *QuestComponent `+"`comp:\"CompTypeQuest\"`"+`
}
`)
	if err := run([]string{"-dir", filepath.Join(root, "game", "entities")}, io.Discard); err != nil {
		t.Fatal(err)
	}
	view, err := os.ReadFile(filepath.Join(root, "game", "view", "entity_player.go"))
	if err != nil {
		t.Fatalf("view entity not generated: %v", err)
	}
	for _, want := range []string{"// Code generated by tool/entity. DO NOT EDIT.", "package view", "type PlayerEntity interface", "entity.IThreadSafeEntity", "Dao() *db.PlayerDao", "BagHolder"} {
		if !strings.Contains(string(view), want) {
			t.Errorf("view entity lacks %q:\n%s", want, view)
		}
	}
	if strings.Contains(string(view), "Quest") {
		t.Errorf("a component without a view Holder is embedded:\n%s", view)
	}
	wire, err := os.ReadFile(filepath.Join(root, "game", "entities", "player", "player_gen_wire.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(wire), "func (e *Player) Bag() view.Bag { return e.bag }") || !strings.Contains(string(wire), `view "example.com/g/game/view"`) {
		t.Errorf("wire lacks the view accessor:\n%s", wire)
	}
	if strings.Contains(string(wire), "Quest() view.") {
		t.Errorf("wire has an accessor for a component without a Holder:\n%s", wire)
	}
	// 实体去掉：view 文件随全量生成删除，手写的 component_*.go 不动。
	write("game/entities/player/player.go", "package player\n")
	if err := run([]string{"-dir", filepath.Join(root, "game", "entities")}, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(root, "game", "view", "entity_player.go")); !os.IsNotExist(err) {
		t.Errorf("view entity of a removed entity survives: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "game", "view", "component_bag.go")); err != nil {
		t.Errorf("hand-written view file removed: %v", err)
	}
}

// 只生成一个实体包时（roost generate 按改动的包跑、或 go:generate）也要删掉已经没有实体的 view 实体文件；
// 共用组件的接线文件手写返回 view 类型的访问器时，实体接口嵌入对应的 Holder。
func TestRunRetiresStaleViewEntitiesOnAPartialScanAndEmbedsHandWrittenAccessors(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/g\n\ngo 1.24\n")
	write("game/view/component_activity.go", "package view\n\ntype Activity interface{ Rearm() error }\n\ntype ActivityHolder interface{ Activity() Activity }\n")
	entityFile := func(name, extra string) string {
		return `package ` + strings.ToLower(name) + `

import (
	db "example.com/g/db"
	"example.com/g/game/view"
	"github.com/tjbdwanghaibo/roost-core/framework/entity"
)

const EntityKind` + name + ` = 1

const CompType` + name + `Activity entity.ComponentType = 1

type ` + name + `ActivityComponent struct{ entity.ComponentBase }

//roost:entity entityKind=EntityKind` + name + `
type ` + name + ` struct {
	*entity.EntityBase
	dao      *db.` + name + `Dao ` + "`dao:\"x\"`" + `
	activity *` + name + `ActivityComponent ` + "`comp:\"CompType" + name + "Activity\"`" + `
}
` + extra
	}
	write("game/entities/guild/guild.go", entityFile("Guild", "\nfunc (e *Guild) Activity() view.Activity { return nil }\n"))
	write("game/entities/clan/clan.go", entityFile("Clan", ""))
	if err := run([]string{"-dir", filepath.Join(root, "game", "entities")}, io.Discard); err != nil {
		t.Fatal(err)
	}
	guild, err := os.ReadFile(filepath.Join(root, "game", "view", "entity_guild.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(guild), "ActivityHolder") {
		t.Errorf("the hand-written view accessor did not embed ActivityHolder:\n%s", guild)
	}
	if clan, _ := os.ReadFile(filepath.Join(root, "game", "view", "entity_clan.go")); strings.Contains(string(clan), "ActivityHolder") {
		t.Errorf("an entity without the accessor embeds ActivityHolder:\n%s", clan)
	}
	// 删掉 Clan 后只生成 guild 包：entity_clan.go 也要删，entity_guild.go 留着。
	if err := os.RemoveAll(filepath.Join(root, "game", "entities", "clan")); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"-dir", filepath.Join(root, "game", "entities", "guild")}, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(root, "game", "view", "entity_clan.go")); !os.IsNotExist(err) {
		t.Errorf("a partial scan left the removed entity's view file: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "game", "view", "entity_guild.go")); err != nil {
		t.Errorf("a partial scan removed a live entity's view file: %v", err)
	}
}
