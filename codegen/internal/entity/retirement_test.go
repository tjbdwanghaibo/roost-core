func TestRunRetiresEntityWireAfterLastMarkerRemoved(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "player.go")
	write := func(marker string) {
		t.Helper()
		if err := os.WriteFile(source, []byte("package game\nconst EntityKindPlayer = 1\n//"+marker+"\ntype Player struct{}\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	wire := filepath.Join(dir, "player_gen_wire.go")
	if _, err := os.Stat(wire); err != nil {
		t.Fatalf("generated wire missing: %v", err)
	}
	guard := guardTestFileFor(wire)
	if err := os.WriteFile(guard, []byte("// Code generated by tool/entity. DO NOT EDIT.\npackage game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	manual := filepath.Join(dir, "manual_gen_wire.go")
	if err := os.WriteFile(manual, []byte("package game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{wire, guard} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Errorf("retired output remains %s: %v", path, err)
		}
	}
	if _, err := os.Stat(manual); err != nil {
		t.Fatalf("manual file removed: %v", err)
	}
}

func TestRunMovesRegistrationWhenFirstSiblingIsRetired(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "entities.go")
	write := func(alphaMarker string) {
		t.Helper()
		body := "package game\nconst (EntityKindAlpha = 1; EntityKindBeta = 2)\n//" + alphaMarker + "\ntype Alpha struct{}\n//roost:entity entityKind=EntityKindBeta\ntype Beta struct{}\n"
		if err := os.WriteFile(source, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "alpha_gen_wire.go")); !os.IsNotExist(err) {
		t.Fatalf("retired sibling wire remains: %v", err)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "beta_gen_wire.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(raw), "func RegisterEntity()") || !strings.Contains(string(raw), "//roost:register phase=entity") {
		t.Fatal("remaining sibling did not take over the package registration")
	}
}
