func TestRunRetiresEntityWireAfterLastMarkerRemoved(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "player.go")
	write := func(marker string) {
		t.Helper()
		if err := os.WriteFile(source, []byte("package game\nconst EntityKindPlayer = 1\n//"+marker+"\ntype Player struct{}\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	wire := filepath.Join(dir, "player_gen_wire.go")
	if _, err := os.Stat(wire); err != nil {
		t.Fatalf("generated wire missing: %v", err)
	}
	guard := guardTestFileFor(wire)
	if err := os.WriteFile(guard, []byte("// Code generated by tool/entity. DO NOT EDIT.\npackage game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	manual := filepath.Join(dir, "manual_gen_wire.go")
	if err := os.WriteFile(manual, []byte("package game\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindPlayer")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{wire, guard} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Errorf("retired output remains %s: %v", path, err)
		}
	}
	if _, err := os.Stat(manual); err != nil {
		t.Fatalf("manual file removed: %v", err)
	}
}

func TestRunMovesRegistrationWhenFirstSiblingIsRetired(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "entities.go")
	write := func(alphaMarker string) {
		t.Helper()
		body := "package game\nconst (EntityKindAlpha = 1; EntityKindBeta = 2)\n//" + alphaMarker + "\ntype Alpha struct{}\n//roost:entity entityKind=EntityKindBeta\ntype Beta struct{}\n"
		if err := os.WriteFile(source, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("roost:entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	write("retired entity entityKind=EntityKindAlpha")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "alpha_gen_wire.go")); !os.IsNotExist(err) {
		t.Fatalf("retired sibling wire remains: %v", err)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "beta_gen_wire.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(raw), "func RegisterEntity()") || !strings.Contains(string(raw), "//roost:register phase=entity") {
		t.Fatal("remaining sibling did not take over the package registration")
	}
}

// v1.47.0：每个实体包生成 lifecycle_gen.go（core 泛型 entitylifecycle 的具名入口）。只有一个实体时用短名
// （player.LifecycleFromRegistry），几个实体共用一个包时带实体名，避免同名冲突；只剩只读 DTO 的包删掉它。
func TestRunGeneratesEntityLifecycle(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("player.go", "package player\nconst EntityKindPlayer = 1\n//roost:entity entityKind=EntityKindPlayer\ntype Player struct{}\n")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	lifecycle := filepath.Join(dir, "lifecycle_gen.go")
	raw, err := os.ReadFile(lifecycle)
	if err != nil {
		t.Fatalf("lifecycle not generated: %v", err)
	}
	for _, want := range []string{
		"// Code generated by tool/entity. DO NOT EDIT.", "package player",
		"type Lifecycle = entitylifecycle.Lifecycle[*Player]",
		"func LifecycleFromRegistry(registry *app.Registry) (*Lifecycle, error)",
		`entitylifecycle.FromRegistry[*Player](registry, EntityKindPlayer, "player", ErrNotFound)`,
		`var ErrNotFound = errors.New("player lifecycle: Entity not found")`,
	} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("lifecycle lacks %q:\n%s", want, raw)
		}
	}
	write("player.go", "package player\nconst (EntityKindPlayer = 1; EntityKindPlayerShadow = 2)\n//roost:entity entityKind=EntityKindPlayer\ntype Player struct{}\n//roost:entity entityKind=EntityKindPlayerShadow\ntype PlayerShadow struct{}\n")
	if err := run([]string{"-dir", dir}, io.Discard); err != nil {
		t.Fatal(err)
	}
	raw, _ = os.ReadFile(lifecycle)
	for _, want := range []string{"func PlayerLifecycleFromRegistry(", "func PlayerShadowLifecycleFromRegistry(", "var ErrPlayerShadowNotFound"} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("two-entity lifecycle lacks %q:\n%s", want, raw)
		}
	}
	if strings.Contains(string(raw), "func LifecycleFromRegistry(") {
		t.Errorf("two entities must not share the short name:\n%s", raw)
	}
}
