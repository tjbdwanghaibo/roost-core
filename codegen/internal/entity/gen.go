const generatorVersion = "v2"

// generate produces the wiring file for an entity that is alone in its
// package. Returns true if the file was written (changed).
func generate(ent EntityDef, pkg string, outFile string, force bool) (bool, error) {
	return generateInPackage(ent, []string{ent.Name}, pkg, outFile, force)
}

// generateInPackage produces the wiring file for one entity of a package that
// holds siblings (sorted entity names, ent.Name among them). Every file declares
// its own register<Name>Entity and once-guard; the package-level RegisterEntity
// that carries the //roost:register marker is emitted once, into the file of
// the first sibling, and calls each of them. Two entities in one package used
// to get two RegisterEntity / registerEntityOnce declarations — generation
// succeeded and the consumer failed to compile (RR-20260909-04).
func generateInPackage(ent EntityDef, siblings []string, pkg string, outFile string, force bool) (bool, error) {
	if len(siblings) == 0 {
		siblings = []string{ent.Name}
	}
	remoteV2 := ent.RemotePolicy == "entity.RemotePolicyManaged"
	if remoteV2 && !ent.RemoteBase {
		return false, fmt.Errorf("entity %s: remote=managed requires embedding *entity.RemoteEntityBase", ent.Name)
	}
	var buf bytes.Buffer

	data := templateData{
		Package:  pkg,
		Entity:   ent,
		Siblings: siblings,
		Primary:  ent.Name == siblings[0],
		HasDaos:  len(ent.Daos) > 0,
		HasComps: len(ent.Components) > 0,
		HasDirty: hasDirtyDao(ent),
		RemoteV2: remoteV2,
	}
	data.NeedsRemove = data.HasDirty && !ent.NoPersist && !data.RemoteV2 && !hasMethod(ent, "PrepareDelete")
	data.ImportBlock = buildImportBlock(ent, data.RemoteV2 || data.NeedsRemove, data.RemoteV2, data.NeedsRemove)

	tmpl, err := template.New("entity_wire").Funcs(template.FuncMap{
		"deref":              derefType,
		"ctor":               constructorName,
		"quote":              quoteString,
		"syncTopic":          syncTopicExpr,
		"syncPackerFactory":  syncPackerFactoryExpr,
		"daoCollectionConst": daoCollectionConstExpr,
		"hasMethod":          hasMethod,
		"join":               strings.Join,
	}).Parse(wireTemplate)
	if err != nil {
		return false, fmt.Errorf("template parse: %w", err)
	}

	if err := tmpl.Execute(&buf, data); err != nil {
		return false, fmt.Errorf("template exec: %w", err)
	}

	content, err := format.Source(buf.Bytes())
	if err != nil {
		return false, fmt.Errorf("format generated source: %w", err)
	}

	// Check if file exists and content is unchanged. The companion guard test
	// is reconciled either way, so a project generated before it existed gets
	// it on the next plain run.
	changed := true
	if !force {
		existing, err := os.ReadFile(outFile)
		if err == nil {
			existingHash := fmt.Sprintf("%x", md5.Sum(existing))
			newHash := fmt.Sprintf("%x", md5.Sum(content))
			if existingHash == newHash {
				changed = false
			}
		}
	}
	if changed {
		if err := os.WriteFile(outFile, content, 0644); err != nil {
			return false, err
		}
	}
	testChanged, err := generateGuardTests(data, outFile, force)
	if err != nil {
		return changed, err
	}
	return changed || testChanged, nil
}

// guardTestFile is the generated companion test for a remote-managed entity's
// wiring: guardTestFileFor("x_gen_wire.go") == "x_gen_wire_test.go".
func guardTestFileFor(outFile string) string {
	return strings.TrimSuffix(outFile, ".go") + "_test.go"
}

// generateGuardTests writes (or removes) the companion test that pins the
// remote-commit guards inside the generated wiring. Those guards live in
// generated code, so the generator's own unit tests cannot reach them; a test
// generated into the business project runs them where they are compiled
// (HANDOFF §4.4 / U-0124). Entities that are not remote-managed, or whose DAOs
// are all cold, get no test — and a stale one from an earlier shape is removed
// so it cannot fail to compile against the new wiring.
func generateGuardTests(data templateData, outFile string, force bool) (bool, error) {
	testFile := guardTestFileFor(outFile)
	hasHotDao := false
	for _, dao := range data.Entity.Daos {
		if !dao.Cold {
			hasHotDao = true
		}
	}
	if !data.RemoteV2 || !hasHotDao {
		if existing, err := os.ReadFile(testFile); err == nil && bytes.HasPrefix(existing, []byte("// Code generated by tool/entity.")) {
			return true, os.Remove(testFile)
		}
		return false, nil
	}
	tmpl, err := template.New("entity_guard_tests").Funcs(template.FuncMap{"firstToLower": firstToLower}).Parse(guardTestTemplate)
	if err != nil {
		return false, fmt.Errorf("guard test template parse: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return false, fmt.Errorf("guard test template exec: %w", err)
	}
	content, err := format.Source(buf.Bytes())
	if err != nil {
		return false, fmt.Errorf("format generated guard tests: %w", err)
	}
	return genutil.WriteIfChanged(testFile, content, force)
}

func firstToLower(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

