func derefType(s string) string {
	if len(s) > 0 && s[0] == '*' {
		return s[1:]
	}
	return s
}

func constructorName(typeName string) string {
	name := derefType(typeName)
	if idx := strings.LastIndex(name, "."); idx >= 0 {
		return name[:idx+1] + "New" + name[idx+1:]
	}
	return "New" + name
}

func quoteString(s string) string {
	return fmt.Sprintf("%q", s)
}

// syncPackerFactoryExpr resolves the one packer factory Core's
// EntitySyncBuilderParam takes. Two marker spellings reach it: `subjectPacker`
// (current) and `syncPacker` (kept working for projects written before the
// two collapsed into one). They name the same thing — a
// `func(entity.IThreadSafeEntity) entity.SubjectSyncPacker` — so a marker
// that sets both is refused at parse time rather than silently picking one
// (RR-20260918-01).
func syncPackerFactoryExpr(e EntityDef) string {
	if e.SubjectPacker != "" {
		return e.SubjectPacker
	}
	return e.SyncPacker
}

// syncTopicExpr renders the marker's value. Three spellings reach here, and
// parse.go has already refused the fourth (a bare identifier, which used to be
// quoted into the string of its own name — RR-20260918-07):
//
//	syncTopic=player               → "player"
//	syncTopic="Player"             → "Player"      (already a literal)
//	syncTopic=clientsync.Topic     → clientsync.Topic
func syncTopicExpr(s string) string {
	if s == "" {
		return `""`
	}
	if quoted, ok := unquoteGoString(s); ok {
		return quoteString(quoted)
	}
	if isConstExpr(s) {
		return s
	}
	return quoteString(s)
}

// unquoteGoString reports whether the marker value was written as a quoted
// literal and returns its contents.
func unquoteGoString(s string) (string, bool) {
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		return s[1 : len(s)-1], true
	}
	return "", false
}

func daoCollectionConstExpr(typeName string) string {
	name := derefType(typeName)
	qualifier := ""
	if idx := strings.LastIndex(name, "."); idx >= 0 {
		qualifier = name[:idx+1]
		name = name[idx+1:]
	}
	return qualifier + name + "Collection"
}

func isConstExpr(s string) bool {
	if strings.ContainsAny(s, "\"'`") {
		return false
	}
	idx := strings.Index(s, ".")
	if idx <= 0 || idx == len(s)-1 {
		return false
	}
	first := s[0]
	if (first < 'A' || first > 'Z') && (first < 'a' || first > 'z') && first != '_' {
		return false
	}
	for _, r := range s[:idx] {
		if (r < 'A' || r > 'Z') && (r < 'a' || r > 'z') && (r < '0' || r > '9') && r != '_' {
			return false
		}
	}
	afterDot := s[idx+1]
	return afterDot >= 'A' && afterDot <= 'Z'
}

func hasDirtyDao(ent EntityDef) bool {
	return len(ent.Daos) > 0
}

func hasMethod(ent EntityDef, name string) bool {
	return ent.ExistingMethods != nil && ent.ExistingMethods[name]
}

func buildImportBlock(ent EntityDef, needsFmt, needsDataEngine, needsNest bool) string {
	var groups [][]string
	std := []string{`"sync"`}
	if needsFmt {
		std = append([]string{`"fmt"`}, std...)
	}
	groups = append(groups, std)

	local := make([]string, 0, len(ent.Imports)+2)
	for _, imp := range ent.Imports {
		if imp.Explicit {
			local = append(local, fmt.Sprintf(`%s "%s"`, imp.Alias, imp.Path))
		} else {
			local = append(local, fmt.Sprintf(`"%s"`, imp.Path))
		}
	}
	if needsDataEngine {
		local = append(local, `"github.com/tjbdwanghaibo/roost-core/dataengine"`)
	}
	if needsNest {
		local = append(local, `"github.com/tjbdwanghaibo/roost-core/nest"`)
	}
	local = append(local, `"github.com/tjbdwanghaibo/roost-core/entity"`)
	groups = append(groups, local)

	var b strings.Builder
	for i, group := range groups {
		if i > 0 {
			b.WriteByte('\n')
		}
		for _, line := range group {
			b.WriteByte('\t')
			b.WriteString(line)
			b.WriteByte('\n')
		}
	}
	return b.String()
}

