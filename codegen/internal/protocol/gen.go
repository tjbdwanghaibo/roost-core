func generateProto(defs *Definitions) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "syntax = \"proto3\";\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", defs.ProtoPackage)
	fmt.Fprintf(&b, "option go_package = %q;\n\n", defs.GoPackage)
	for _, enum := range defs.Enums {
		fmt.Fprintf(&b, "// roost:source=go_def\n")
		fmt.Fprintf(&b, "enum %s {\n", enum.Name)
		for _, value := range enum.Values {
			fmt.Fprintf(&b, "  %s = %d;\n", value.Name, value.Value)
		}
		fmt.Fprintf(&b, "}\n\n")
	}
	for _, st := range defs.Structs {
		fmt.Fprintf(&b, "// roost:source=go_def\n")
		fmt.Fprintf(&b, "message %s {\n", st.Name)
		writtenOneofs := make(map[string]bool)
		for _, f := range st.Fields {
			if f.Oneof == "" {
				fmt.Fprintf(&b, "  %s %s = %d;\n", f.ProtoType, f.ProtoName, f.Number)
				continue
			}
			if writtenOneofs[f.Oneof] {
				continue
			}
			writtenOneofs[f.Oneof] = true
			fmt.Fprintf(&b, "  oneof %s {\n", f.Oneof)
			for _, item := range st.Fields {
				if item.Oneof == f.Oneof {
					fmt.Fprintf(&b, "    %s %s = %d;\n", item.ProtoType, item.ProtoName, item.Number)
				}
			}
			fmt.Fprintf(&b, "  }\n")
		}
		fmt.Fprintf(&b, "}\n\n")
	}
	return b.Bytes(), nil
}

func generateMsgIDGo(defs *Definitions) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tool/protocol. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "package msgid\n\n")
	fmt.Fprintf(&b, "const (\n")
	for _, msg := range defs.Messages {
		base := msgName(msg)
		fmt.Fprintf(&b, "\tMsg%s uint32 = %d\n", base, msg.ReqID)
	}
	for _, push := range defs.Pushes {
		base := pushName(push)
		fmt.Fprintf(&b, "\tMsg%s uint32 = %d\n", base, push.MsgID)
	}
	fmt.Fprintf(&b, ")\n")

	tags := collectProtocolTags(defs)
	if len(tags) > 0 {
		fmt.Fprintf(&b, "\nconst (\n")
		for _, tag := range tags {
			fmt.Fprintf(&b, "\t%s = %q\n", tagConstName(tag), tag)
		}
		fmt.Fprintf(&b, ")\n")
	}
	fmt.Fprintf(&b, "\nvar msgTags = map[uint32][]string{\n")
	for _, msg := range defs.Messages {
		if len(msg.Tags) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\tMsg%s: %s,\n", msgName(msg), tagConstList(msg.Tags))
	}
	for _, push := range defs.Pushes {
		if len(push.Tags) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\tMsg%s: %s,\n", pushName(push), tagConstList(push.Tags))
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "func MsgTags(msgID uint32) []string {\n")
	fmt.Fprintf(&b, "\ttags := msgTags[msgID]\n")
	fmt.Fprintf(&b, "\tif len(tags) == 0 {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(&b, "\tout := make([]string, len(tags))\n")
	fmt.Fprintf(&b, "\tcopy(out, tags)\n")
	fmt.Fprintf(&b, "\treturn out\n")
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "func MsgHasTag(msgID uint32, tag string) bool {\n")
	fmt.Fprintf(&b, "\tfor _, cur := range msgTags[msgID] {\n")
	fmt.Fprintf(&b, "\t\tif cur == tag {\n\t\t\treturn true\n\t\t}\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn false\n")
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "func MsgHasAnyTag(msgID uint32, tags ...string) bool {\n")
	fmt.Fprintf(&b, "\tif len(tags) == 0 {\n\t\treturn false\n\t}\n")
	fmt.Fprintf(&b, "\tfor _, tag := range tags {\n")
	fmt.Fprintf(&b, "\t\tif MsgHasTag(msgID, tag) {\n\t\t\treturn true\n\t\t}\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn false\n")
	fmt.Fprintf(&b, "}\n")
	return formatGo(b.Bytes())
}

func generateBindGo(defs *Definitions) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tool/protocol. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "package player_bind\n\n")
	if len(defs.Messages) == 0 && len(defs.Pushes) == 0 {
		return formatGo(b.Bytes())
	}
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+PlayerAgentImportSuffix)
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+"/protocol/msgid")
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+PBImportSuffix)
	fmt.Fprintf(&b, ")\n\n")
	for _, msg := range defs.Messages {
		name := msgName(msg)
		if msg.Resp != "" {
			fmt.Fprintf(&b, "func Register%s(reg *player_agent.ProtocolRegistry, handler func(*player_agent.Context, *pb.%s) (*pb.%s, error)) error {\n", name, msg.Req, msg.Resp)
			fmt.Fprintf(&b, "\treturn player_agent.RegisterProtocol[*pb.%s, *pb.%s](reg, msgid.Msg%s, msgid.Msg%s, pb.Unmarshal%s, pb.Marshal%s, handler)\n", msg.Req, msg.Resp, name, name, msg.Req, msg.Resp)
			fmt.Fprintf(&b, "}\n\n")
		} else {
			fmt.Fprintf(&b, "func Register%s(reg *player_agent.ProtocolRegistry, handler func(*player_agent.Context, *pb.%s) error) error {\n", name, msg.Req)
			fmt.Fprintf(&b, "\treturn player_agent.RegisterNotify[*pb.%s](reg, msgid.Msg%s, pb.Unmarshal%s, handler)\n", msg.Req, name, msg.Req)
			fmt.Fprintf(&b, "}\n\n")
		}
	}
	for _, push := range defs.Pushes {
		name := pushName(push)
		fmt.Fprintf(&b, "func Register%sEncoder(reg *player_agent.ProtocolRegistry) error {\n", name)
		fmt.Fprintf(&b, "\treturn player_agent.RegisterTypedEncoder[*pb.%s](reg, msgid.Msg%s, pb.Marshal%s)\n", push.Msg, name, push.Msg)
		fmt.Fprintf(&b, "}\n\n")
	}
	return formatGo(b.Bytes())
}

func generateRobotProtocolGo(defs *Definitions) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tool/protocol. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "package protocol\n\n")
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+"/protocol/msgid")
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+PBImportSuffix)
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "func RegisterDefaults(r *Registry) {\n")
	fmt.Fprintf(&b, "\tif r == nil {\n")
	fmt.Fprintf(&b, "\t\treturn\n")
	fmt.Fprintf(&b, "\t}\n")

	messages := append([]MsgDef(nil), defs.Messages...)
	sort.Slice(messages, func(i, j int) bool { return messages[i].ReqID < messages[j].ReqID })
	for _, msg := range messages {
		name := msgName(msg)
		fmt.Fprintf(&b, "\tr.MustRegisterEncoder(msgid.Msg%s, encodeTyped[*pb.%s](msgid.Msg%s, pb.Marshal%s))\n", name, msg.Req, name, msg.Req)
		if msg.Resp != "" {
			fmt.Fprintf(&b, "\tr.MustRegisterDecoder(msgid.Msg%s, decodeTyped(msgid.Msg%s, pb.Unmarshal%s))\n", name, name, msg.Resp)
		}
	}

	pushes := append([]PushDef(nil), defs.Pushes...)
	sort.Slice(pushes, func(i, j int) bool { return pushes[i].MsgID < pushes[j].MsgID })
	for _, push := range pushes {
		name := pushName(push)
		fmt.Fprintf(&b, "\tr.MustRegisterDecoder(msgid.Msg%s, decodeTyped(msgid.Msg%s, pb.Unmarshal%s))\n", name, name, push.Msg)
	}
	fmt.Fprintf(&b, "}\n")
	return formatGo(b.Bytes())
}

func generateProtocolHandlerFiles(defs *Definitions) (map[string][]byte, error) {
	groups := make(map[string][]MsgDef)
	for _, msg := range defs.Messages {
		if msg.Handler == "" {
			continue
		}
		groups[msg.Handler] = append(groups[msg.Handler], msg)
	}
	if len(groups) == 0 {
		return nil, nil
	}

	domains := make([]string, 0, len(groups))
	for domain := range groups {
		domains = append(domains, domain)
	}
	sort.Strings(domains)

	files := make(map[string][]byte, len(domains))
	for _, domain := range domains {
		content, err := generateProtocolHandlerGo(defs.ModulePath, domain, groups[domain])
		if err != nil {
			return nil, err
		}
		files[filepath.Join(domain, "protocol_gen.go")] = content
	}
	return files, nil
}

func generateProtocolHandlerGo(modulePath string, domain string, messages []MsgDef) ([]byte, error) {
	sort.Slice(messages, func(i, j int) bool { return messages[i].ReqID < messages[j].ReqID })

	displayName := protocolHandlerDisplayName(domain)
	packageName := protocolHandlerPackageName(domain)
	controllerAlias := protocolControllerAlias(domain)
	controllerType := displayName + "Controller"
	registerName := "Register" + displayName + "PlayerProtocols"

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tool/protocol. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"github.com/tjbdwanghaibo/roost-core/app\"\n")
	fmt.Fprintf(&b, "\t%s %q\n", controllerAlias, modulePath+"/game/controllers/"+domain)
	fmt.Fprintf(&b, "\t%q\n", modulePath+PlayerAgentImportSuffix)
	fmt.Fprintf(&b, "\t%q\n", modulePath+PBImportSuffix)
	fmt.Fprintf(&b, "\tplayerbind %q\n", modulePath+"/protocol/player_bind")
	fmt.Fprintf(&b, ")\n\n")

	fmt.Fprintf(&b, "type %s interface {\n", controllerType)
	for _, msg := range messages {
		name := msgName(msg)
		if msg.Resp != "" {
			fmt.Fprintf(&b, "\tHandle%s(ctx *player_agent.Context, req *pb.%s) (*pb.%s, error)\n", name, msg.Req, msg.Resp)
			continue
		}
		fmt.Fprintf(&b, "\tHandle%s(ctx *player_agent.Context, req *pb.%s) error\n", name, msg.Req)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "func %s(reg *player_agent.ProtocolRegistry, r *app.Registry) error {\n", registerName)
	fmt.Fprintf(&b, "\tctl, err := %s.FromRegistry(r)\n", controllerAlias)
	fmt.Fprintf(&b, "\tif err != nil {\n")
	fmt.Fprintf(&b, "\t\treturn err\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn %sWith(reg, ctl)\n", registerName)
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "func %sWith(reg *player_agent.ProtocolRegistry, ctl %s) error {\n", registerName, controllerType)
	for i, msg := range messages {
		name := msgName(msg)
		if i == len(messages)-1 {
			fmt.Fprintf(&b, "\treturn playerbind.Register%s(reg, ctl.Handle%s)\n", name, name)
			continue
		}
		fmt.Fprintf(&b, "\tif err := playerbind.Register%s(reg, ctl.Handle%s); err != nil {\n", name, name)
		fmt.Fprintf(&b, "\t\treturn err\n")
		fmt.Fprintf(&b, "\t}\n")
	}
	fmt.Fprintf(&b, "}\n")

	return formatGo(b.Bytes())
}

func generateProtocolBootstrap(defs *Definitions, handlerImportBase string) ([]byte, error) {
	domainsSet := make(map[string]bool)
	for _, message := range defs.Messages {
		if message.Handler != "" {
			domainsSet[message.Handler] = true
		}
	}
	domains := make([]string, 0, len(domainsSet))
	for domain := range domainsSet {
		domains = append(domains, domain)
	}
	sort.Strings(domains)
	if len(domains) > 0 && strings.TrimSpace(handlerImportBase) == "" {
		return nil, fmt.Errorf("protocol bootstrap: handler import base is required for controller domains %s", strings.Join(domains, ","))
	}

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by tool/protocol. DO NOT EDIT.")
	fmt.Fprintln(&b, "package protocol_bootstrap")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "import (")
	fmt.Fprintln(&b, "\t\"fmt\"")
	fmt.Fprintln(&b, "\t\"github.com/tjbdwanghaibo/roost-core/app\"")
	fmt.Fprintf(&b, "\t%q\n", defs.ModulePath+PlayerAgentImportSuffix)
	if len(defs.Pushes) > 0 {
		fmt.Fprintf(&b, "\tplayerbind %q\n", defs.ModulePath+"/protocol/player_bind")
	}
	for _, domain := range domains {
		alias := protocolControllerAlias(domain) + "protocol"
		fmt.Fprintf(&b, "\t%s %q\n", alias, strings.TrimSuffix(handlerImportBase, "/")+"/"+domain)
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "func RegisterPlayerProtocols(protocols *player_agent.ProtocolRegistry, registry *app.Registry) error {")
	fmt.Fprintln(&b, "\tif protocols == nil || registry == nil {")
	fmt.Fprintln(&b, "\t\treturn fmt.Errorf(\"player protocol bootstrap: protocols and registry are required\")")
	fmt.Fprintln(&b, "\t}")
	for _, domain := range domains {
		alias := protocolControllerAlias(domain) + "protocol"
		fmt.Fprintf(&b, "\tif err := %s.Register%sPlayerProtocols(protocols, registry); err != nil {\n\t\treturn err\n\t}\n", alias, protocolHandlerDisplayName(domain))
	}
	for _, push := range defs.Pushes {
		fmt.Fprintf(&b, "\tif err := playerbind.Register%sEncoder(protocols); err != nil {\n\t\treturn err\n\t}\n", pushName(push))
	}
	fmt.Fprintln(&b, "\treturn nil")
	fmt.Fprintln(&b, "}")
	return formatGo(b.Bytes())
}

func protocolHandlerPackageName(domain string) string {
	return strings.ReplaceAll(domain, "_", "") + "handler"
}

func protocolControllerAlias(domain string) string {
	return strings.ReplaceAll(domain, "_", "") + "controller"
}

func protocolHandlerDisplayName(domain string) string {
	if name := protocolHandlerDisplayNames[domain]; name != "" {
		return name
	}
	return exportName(domain)
}

