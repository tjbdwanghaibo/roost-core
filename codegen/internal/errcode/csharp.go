package errcode

import (
	"bytes"
	"fmt"
	"strings"
	"unicode"
)

// CSharpGeneratedHeader 是 ErrorCodes.cs 的第一行。
const CSharpGeneratedHeader = "// Code generated by tool/errcode. DO NOT EDIT."

// Definitions 返回 root 下全部 errcode.Define（按码排序），码或名字重复时报错：与写 CSV 的同一份检查。
// roost generate 的 client_export 用它写 ErrorCodes.cs 与导出清单。
func Definitions(root string) ([]Definition, error) {
	return extractDefinitions(root)
}

// GenerateCSharp 产出客户端错误码表 ErrorCodes.cs：每个码一个 int 常量（名字是 errcode 名的 PascalCase，
// 说明写在 summary 里），另有按码查名字与说明的 Name / Message。两个名字转成同一个 C# 标识符时报错。
func GenerateCSharp(defs []Definition, namespace string) ([]byte, error) {
	idents := make(map[string]string, len(defs))
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n#nullable disable\nnamespace %s\n{\n    public static class ErrorCodes\n    {\n", CSharpGeneratedHeader, namespace)
	names := make([]string, len(defs))
	for i, def := range defs {
		ident, err := csharpIdentifier(def.Name)
		if err != nil {
			return nil, fmt.Errorf("errcode %d (%s): %w", def.Code, def.File, err)
		}
		if other, exists := idents[ident]; exists {
			return nil, fmt.Errorf("errcode names %q and %q both become C# identifier %s; rename one", other, def.Name, ident)
		}
		idents[ident] = def.Name
		names[i] = ident
		fmt.Fprintf(&b, "        /// <summary>%s</summary>\n        public const int %s = %d;\n", xmlEscape(def.Message), ident, def.Code)
	}
	b.WriteString("\n        /// <summary>errcode.Define 的名字；未知码返回 null。</summary>\n        public static string Name(int code)\n        {\n            switch (code)\n            {\n")
	for i, def := range defs {
		fmt.Fprintf(&b, "                case %s: return %s;\n", names[i], csharpString(def.Name))
	}
	b.WriteString("                default: return null;\n            }\n        }\n\n")
	b.WriteString("        /// <summary>errcode.Define 的说明；未知码返回 null。</summary>\n        public static string Message(int code)\n        {\n            switch (code)\n            {\n")
	for i, def := range defs {
		fmt.Fprintf(&b, "                case %s: return %s;\n", names[i], csharpString(def.Message))
	}
	b.WriteString("                default: return null;\n            }\n        }\n    }\n}\n")
	return b.Bytes(), nil
}

// csharpIdentifier 把 errcode 名（通常是 snake_case，也可能带点）转成 PascalCase：字母数字以外的字符都是分词符。
func csharpIdentifier(name string) (string, error) {
	var b strings.Builder
	upper := true
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) || r > unicode.MaxASCII {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	ident := b.String()
	if ident == "" {
		return "", fmt.Errorf("name %q has no ASCII letter or digit for a C# identifier", name)
	}
	if ident[0] >= '0' && ident[0] <= '9' {
		ident = "_" + ident
	}
	return ident, nil
}

// csharpString 写 C# 普通字符串字面量：反斜杠、引号与控制字符转义，其余（含中文）原样。
func csharpString(text string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range text {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f || r == 0x2028 || r == 0x2029 || r == 0x85 {
				fmt.Fprintf(&b, `\u%04x`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// xmlEscape 让说明能放进 /// <summary>：转义 XML 特殊字符，换行改空格（文档注释只有一行）。
func xmlEscape(text string) string {
	text = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "\r\n", " ", "\n", " ", "\r", " ").Replace(text)
	return text
}
