package eventgen

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

func generateHandler(h *HandlerInfo, outFile string, force bool) (bool, error) {
	tmpl, err := template.New("handler").Funcs(template.FuncMap{
		"recvVar": recvVar,
	}).Parse(handlerTemplate)
	if err != nil {
		return false, fmt.Errorf("template parse: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, h); err != nil {
		return false, fmt.Errorf("template exec: %w", err)
	}

	return writeIfChanged(buf.Bytes(), outFile, force)
}

// recvVar returns the receiver variable name (first letter lowercase).
// If it conflicts with "d" (the event data param), use "e" instead.
func recvVar(receiver string) string {
	if len(receiver) == 0 {
		return "r"
	}
	v := strings.ToLower(receiver[:1])
	if v == "d" {
		return "e"
	}
	return v
}

var handlerTemplate = `// Code generated by tool/eventgen. DO NOT EDIT.
package {{.Package}}

import (
	"{{.EventPkg}}"
	frameworkEvent "github.com/tjbdwanghaibo/roost-core/event"
)

func ({{recvVar .Receiver}} *{{.Receiver}}) InitSub() {
{{- range .Events}}
	{{recvVar $.Receiver}}.SubEvent(event.EventType{{.Suffix}})
{{- end}}
}

func ({{recvVar .Receiver}} *{{.Receiver}}) SyncHandleEvent(d frameworkEvent.EventData) {
	switch d.(type) {
{{- range .Events}}
	case *event.Event{{.Suffix}}:
		{{recvVar $.Receiver}}.DealEvent{{.Suffix}}(d.(*event.Event{{.Suffix}}))
{{- end}}
	}
}
`
