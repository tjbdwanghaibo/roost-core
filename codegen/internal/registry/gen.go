package registry

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
	"unicode"
)

// OutputPath is where the aggregate lives, relative to the project root.
const OutputPath = "internal/registry/generated.go"

// Generate writes the aggregate and reports whether the file changed, so a
// no-op `roost generate` run stays quiet and leaves the mtime alone.
func Generate(root string, modulePath string, registrations []Registration) (bool, error) {
	content, err := render(modulePath, registrations)
	if err != nil {
		return false, err
	}
	outFile := filepath.Join(root, filepath.FromSlash(OutputPath))
	if existing, readErr := os.ReadFile(outFile); readErr == nil && bytes.Equal(existing, content) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(outFile), 0o755); err != nil {
		return false, fmt.Errorf("registry: mkdir %s: %w", filepath.Dir(outFile), err)
	}
	if err := os.WriteFile(outFile, content, 0o644); err != nil {
		return false, fmt.Errorf("registry: write %s: %w", outFile, err)
	}
	return true, nil
}

type importSpec struct {
	Alias string
	Path  string
}

type call struct {
	// Expr is the call as it appears in the generated source, e.g.
	// "entitiesplayer.RegisterEntity()".
	Expr string
	// Qualified is the full import path plus function name, used verbatim in
	// the wrapped error so a failure names the package, not just the alias.
	Qualified    string
	ReturnsError bool
}

type phaseGroup struct {
	Name  string
	Calls []call
}

type templateData struct {
	Imports []importSpec
	Phases  []phaseGroup
}

var aggregateTemplate = template.Must(template.New("registry").Parse(`// Code generated by roost-codegen. DO NOT EDIT.

// Package registry performs every static registration in this project: entity
// kinds and builders, component factories, config tables, protocol handlers
// and routes.
//
// RegisterAll is called once from bootstrap.New before app.New, because all of
// it must be in place before any Mod's Init runs. There is deliberately no mod
// for this: an entity builder registered inside a mod's Start is already too
// late for a mod that resolves entities in Provide.
//
// To add to the list, mark a package-level registration function and run
// roost generate:
//
//	//roost:register phase=component
//	func RegisterComponent() { ... }
package registry

import (
	"fmt"
	"sync"

	"github.com/tjbdwanghaibo/roost-core/entity"
{{- if .Imports}}
{{range .Imports}}
	{{.Alias}} "{{.Path}}"
{{- end}}
{{- end}}
)

var (
	registerOnce sync.Once
	registerErr  error
)

// RegisterAll runs the registrations once and returns the same result to every
// later caller. It returns an error rather than panicking: a failed
// registration is a diagnosable conflict — a duplicate id, a malformed config
// table — and belongs in the startup error returned to main.
func RegisterAll() error {
	registerOnce.Do(func() { registerErr = registerAll() })
	return registerErr
}

func registerAll() error {
{{- if not .Phases}}
	// No //roost:register functions in this project yet.
{{- end}}
{{- range .Phases}}

	// phase: {{.Name}}
{{- range .Calls}}
{{- if .ReturnsError}}
	if err := {{.Expr}}; err != nil {
		return fmt.Errorf("registry: {{.Qualified}}: %w", err)
	}
{{- else}}
	{{.Expr}}
{{- end}}
{{- end}}
{{- end}}

	// Every registration has run, which makes this the one place in the
	// project that can check the entity registry as a whole: a remote-managed
	// kind outside the remote category, a kind in a category nobody declared,
	// a kind in the reserved unknown category. Checked anywhere earlier it
	// would report kinds that are merely not registered yet.
	if err := entity.ValidateEntityRegistry(); err != nil {
		return fmt.Errorf("registry: %w", err)
	}

	return nil
}
`))

// ownImportPath is the aggregate's own package; registrations that live
// there (the generated nest aggregate does) are called unqualified, since a
// package cannot import itself.
func ownImportPath(modulePath string) string {
	return strings.TrimSuffix(modulePath, "/") + "/" + strings.TrimSuffix(OutputPath[:strings.LastIndex(OutputPath, "/")], "/")
}

func render(modulePath string, registrations []Registration) ([]byte, error) {
	own := ownImportPath(modulePath)
	external := make([]Registration, 0, len(registrations))
	for _, registration := range registrations {
		if registration.ImportPath != own {
			external = append(external, registration)
		}
	}
	aliases := importAliases(external)
	data := templateData{Imports: make([]importSpec, 0, len(aliases))}

	paths := make([]string, 0, len(aliases))
	for path := range aliases {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		data.Imports = append(data.Imports, importSpec{Alias: aliases[path], Path: path})
	}

	// registrations arrive already sorted into execution order, so grouping is
	// a single pass and the phase order is whatever Scan established.
	for _, registration := range registrations {
		expr := registration.Func + "()"
		if registration.ImportPath != own {
			expr = aliases[registration.ImportPath] + "." + expr
		}
		entry := call{
			Expr:         expr,
			Qualified:    registration.ImportPath + "." + registration.Func,
			ReturnsError: registration.ReturnsError,
		}
		if last := len(data.Phases) - 1; last >= 0 && data.Phases[last].Name == registration.Phase {
			data.Phases[last].Calls = append(data.Phases[last].Calls, entry)
			continue
		}
		data.Phases = append(data.Phases, phaseGroup{Name: registration.Phase, Calls: []call{entry}})
	}

	var buf bytes.Buffer
	if err := aggregateTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("registry: execute template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("registry: format generated source: %w", err)
	}
	return formatted, nil
}

// importAliases assigns one deterministic alias per import path. A game
// project routinely has two packages with the same base name
// (game/entities/player and game/components/player), so the alias grows from
// the tail of the path until it is unique instead of relying on the base name.
func importAliases(registrations []Registration) map[string]string {
	paths := make([]string, 0, len(registrations))
	seen := make(map[string]bool, len(registrations))
	for _, registration := range registrations {
		if seen[registration.ImportPath] {
			continue
		}
		seen[registration.ImportPath] = true
		paths = append(paths, registration.ImportPath)
	}
	sort.Strings(paths)

	used := make(map[string]bool, len(aggregateReservedNames))
	for _, name := range aggregateReservedNames {
		used[name] = true
	}
	aliases := make(map[string]string, len(paths))
	for _, path := range paths {
		aliases[path] = uniqueAlias(path, used)
		used[aliases[path]] = true
	}
	return aliases
}

// aggregateReservedNames are the identifiers the generated file already uses:
// its own package name, its imports, and the local it binds in the error
// checks. A dynamic alias that lands on one of these produces a file with two
// imports under one name, or shadows the local — either way the consumer does
// not compile. "entity" is on the list because the template calls
// entity.ValidateEntityRegistry at the end, and a business registration
// package whose path ends in /entity used to be given exactly that alias
// (RR-20260910-06). Keep this in step with the template's import block.
var aggregateReservedNames = []string{"registry", "sync", "fmt", "err", "entity"}

func uniqueAlias(path string, used map[string]bool) string {
	segments := strings.Split(path, "/")
	alias := ""
	for i := len(segments) - 1; i >= 0; i-- {
		alias = sanitizeIdent(segments[i]) + alias
		if alias != "" && !used[alias] {
			return alias
		}
	}
	base := alias
	if base == "" {
		base = "pkg"
	}
	for counter := 2; ; counter++ {
		candidate := fmt.Sprintf("%s%d", base, counter)
		if !used[candidate] {
			return candidate
		}
	}
}

// sanitizeIdent keeps only letters and digits so a path segment like
// "player_view" or "v2" becomes a legal identifier fragment. A segment that is
// all digits would start an identifier with a digit, so it is prefixed.
func sanitizeIdent(segment string) string {
	var out strings.Builder
	for _, r := range segment {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			out.WriteRune(unicode.ToLower(r))
		}
	}
	result := out.String()
	if result != "" && unicode.IsDigit(rune(result[0])) {
		return "p" + result
	}
	return result
}
